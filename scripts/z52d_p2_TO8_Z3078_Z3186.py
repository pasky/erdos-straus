# Z3186: distance of -1 from 1 in (Z/e)* generated by ±(prime-factor classes of N_e), e≡3 mod 4 window, hard primes
def dist_to_minus1(e, gens):
    gens = list({g % e for g in gens if gcd(g, e) == 1}); gens = gens + [(-g) % e for g in gens]
    frontier = {1}; seen = {1}; d = 0
    while frontier:
        if (e - 1) in frontier: return d
        nxt = set()
        for x in frontier:
            for g in gens:
                y = (x * g) % e
                if y not in seen: seen.add(y); nxt.add(y)
        frontier = nxt; d += 1
    return None
