def two_term(a, b):
    g = gcd(a, b); a //= g; b //= g
    if a == 1: return True
    fb = factorint(b); f2 = {q: 2 * e for q, e in fb.items()}
    ds = [1]
    for q, e in f2.items(): ds = [d * q ** k for d in ds for k in range(e + 1)]
    return any((d + b) % a == 0 and ((b * b // d) + b) % a == 0 for d in ds)
def three_term(m, p):
    # m/p = 1/x+1/y+1/z ; x ranges over [ceil(p/m), floor(3p/m)]
    for x in range(-(-p // m), (3 * p) // m + 1):
        a = m * x - p
        if a <= 0: continue
        if two_term(a, p * x): return True
    return False
