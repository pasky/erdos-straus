"""O194 §5: no Brauer–Manin obstruction for the Schinzel surface m/n = 1/x + 1/y + 1/z (positive integers) at the
failing primes.  Br U / Br Q = Z/2 generated by alpha = (-u1/u3, -u2/u3) (BL Thm 1.6 + Remark 1.10: the surfaces
m/n are Q-isomorphic to U_n).  Certificate: a rational point P0 with x, y, z > 0 (real component in U(R)+),
integral outside a finite set T, and for v in T a rational point P1 integral at v with the same inv_v alpha.
Hilbert symbols over Q_v computed by the explicit formulas (Serre, Cours d'arithmetique III.1.2), all places; the
global reciprocity product is asserted for every point used.  usage: tf_schinzel_bm.py m p [p ...]"""
import sys
from fractions import Fraction as F
from sympy import factorint


def sqfree_int(q):
    """rational q != 0 -> integer in the same square class (q * den^2)."""
    q = F(q)
    return q.numerator * q.denominator


def hilbert(a, b, p):
    """(a, b)_p in {+1, -1} for rationals a, b; p prime or 0 (= infinity)."""
    a, b = sqfree_int(a), sqfree_int(b)
    if p == 0:
        return -1 if (a < 0 and b < 0) else 1
    def split(x):
        k = 0
        while x % p == 0:
            x //= p; k += 1
        return k, x
    al, u = split(a); be, v = split(b)
    if p == 2:
        eps = lambda t: ((t - 1) // 2) % 2
        om = lambda t: ((t * t - 1) // 8) % 2
        e = (eps(u) * eps(v) + al * om(v) + be * om(u)) % 2
        return -1 if e else 1
    leg = lambda t: 1 if pow(t % p, (p - 1) // 2, p) == 1 else -1
    s = (-1) ** ((al * be * ((p - 1) // 2)) % 2)
    if be % 2:
        s *= leg(u)
    if al % 2:
        s *= leg(v)
    return s


def point(m, n, x, y):
    r = F(m, n) - F(1, x) - F(1, y)
    if r == 0:
        return None
    return (F(x), F(y), 1 / r)


def places(P):
    ps = {2}
    for t in P:
        for w in (t.numerator, t.denominator):
            ps |= set(factorint(abs(w)))
    return ps


def invs(P):
    x, y, z = P
    a, b = -x / z, -y / z
    d = {p: hilbert(a, b, p) for p in places(P) | {0}}
    prod = 1
    for s in d.values():
        prod *= s
    assert prod == 1, (P, d)  # Hilbert reciprocity (all other places: units -> +1)
    return d


def bad(P):
    return {p for t in P for p in factorint(t.denominator)}


def certificate(m, n, R=200):
    pts = [P for x in range(1, R) for y in range(x, R) for P in [point(m, n, x, y)] if P]
    pts.sort(key=lambda P: len(bad(P)))
    for P0 in pts:
        if P0[2] <= 0:
            continue
        T = sorted(bad(P0))
        if len(T) != 1:
            continue
        q = T[0]
        i0 = invs(P0).get(q, 1)
        for P1 in pts:
            if q not in bad(P1) and invs(P1).get(q, 1) == i0:
                return P0, q, P1, i0
    return None


if __name__ == '__main__':
    m = int(sys.argv[1])
    for n in map(int, sys.argv[2:]):
        c = certificate(m, n)
        print(f"m = {m}, n = {n}:", "NO certificate found" if c is None else
              f"P0 = {tuple(str(t) for t in c[0])} (positive), T = {{{c[1]}}}, P1 = {tuple(str(t) for t in c[2])}, "
              f"inv_q = {c[3]} for both")
