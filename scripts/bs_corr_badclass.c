/* bs_corr_badclass.c  (O146 memo b).  Fixed prime p; slices II{a,d}: N = p + 4a^2 d, q = 4ad,
   target: a divisor f | N with f = -1 (mod q).  Classify each slice with 4a^2 d <= p + 2a, q <= Qmax:
     H : hit (some divisor f = -1 mod q)
     P : N prime (and not a hit)
     G : -1 not in the subgroup of (Z/q)^* generated by the prime factors of N coprime to q
         ("character-explained": some character mod q is 1 on all of them and -1 at -1)
         (counter cGh: those where no QUADRATIC character mod q does it)
     A : -1 in that subgroup, but no divisor of N hits (exponent/size-limited: "accidental")
   Usage: bs_corr_badclass p Qmax                                                              */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
typedef long long ll;
static int *stamp; static int *queue; static int curstamp=0;
static int leg(ll x, ll r){ x%=r; if(x<0)x+=r; ll e=(r-1)/2, b=x, res=1; while(e){ if(e&1) res=res*b%r; b=b*b%r; e>>=1;} return res==1?0:1; }
/* sign vector (bitmask) of x mod q: odd primes r|q -> Legendre; 2^s|q: s>=2 chi_{-4}, s>=3 chi_8 */
static unsigned long long sgn(ll x, ll q){ unsigned long long v=0; int bit=0; ll m=q; int s=0; while(m%2==0){m/=2;s++;}
  if(s>=2){ if(x%4==3) v|=1ULL<<bit; bit++; } if(s>=3){ ll t=x%8; if(t==3||t==5) v|=1ULL<<bit; bit++; }
  for(ll r=3; r*r<=m; r+=2) if(m%r==0){ while(m%r==0) m/=r; if(leg(x,r)) v|=1ULL<<bit; bit++; }
  if(m>1){ if(leg(x,m)) v|=1ULL<<bit; bit++; } return v; }
static int inspan(unsigned long long *g, int k, unsigned long long t){ /* is t in F2-span of g[0..k) */
  unsigned long long basis[64]; int nb=0;
  for(int i=0;i<k;i++){ unsigned long long x=g[i]; for(int j=0;j<nb;j++){ unsigned long long hb=1ULL<<(63-__builtin_clzll(basis[j])); if(x&hb) x^=basis[j]; }
    if(x){ basis[nb++]=x; /* keep reduced: sort by top bit desc */ for(int j=nb-1;j>0 && basis[j]>basis[j-1];j--){unsigned long long tt=basis[j];basis[j]=basis[j-1];basis[j-1]=tt;} } }
  for(int j=0;j<nb;j++){ unsigned long long hb=1ULL<<(63-__builtin_clzll(basis[j])); if(t&hb) t^=basis[j]; }
  return t==0; }
static ll gcdll(ll a, ll b){ while(b){ ll t=a%b; a=b; b=t;} return a; }
int main(int argc, char **argv){
  ll p=atoll(argv[1]), Qmax=atoll(argv[2]);
  stamp=calloc(Qmax+1,sizeof(int)); queue=malloc((Qmax+1)*sizeof(int));
  ll cH=0,cP=0,cG=0,cA=0,cGh=0; ll byscale[64][4]; memset(byscale,0,sizeof byscale);
  for(ll a=1; 4*a*a <= p+2*a; a++) for(ll d=1; 4*a*a*d <= p+2*a; d++){
    ll q=4*a*d; if(q>Qmax) break;
    ll N=p+4*a*a*d, m=N; ll pr[64]; int ex[64]; int k=0;
    for(ll t=2; t*t<=m; t++) if(m%t==0){ pr[k]=t; ex[k]=0; while(m%t==0){m/=t; ex[k]++;} k++; }
    if(m>1){ pr[k]=m; ex[k]=1; k++; }
    /* enumerate divisors coprime to q, test class */
    int hit=0; { ll divs[4096]; int nd=1; divs[0]=1;
      for(int i=0;i<k;i++){ if(gcdll(pr[i],q)>1) continue; int cur=nd; ll pw=1;
        for(int e=1;e<=ex[i];e++){ pw*=pr[i]; for(int j=0;j<cur;j++) divs[nd++]=divs[j]*pw; } }
      for(int j=0;j<nd;j++) if(divs[j]%q==q-1){ hit=1; break; } }
    int cls;
    if(hit) cls=0;
    else if(k==1 && ex[0]==1) cls=1;
    else { /* BFS closure of subgroup generated by residues of coprime prime factors */
      curstamp++; int h=0,t=0; queue[t++]=1; stamp[1]=curstamp; int minus1=0;
      while(h<t){ ll x=queue[h++]; if(x==(q-1)%q) { minus1=1; break; }
        for(int i=0;i<k;i++){ if(gcdll(pr[i],q)>1) continue; ll y=(x*(pr[i]%q))%q;
          if(stamp[y]!=curstamp){ stamp[y]=curstamp; queue[t++]=y; } } }
      if(q==2) minus1=1;
      cls = minus1 ? 3 : 2;
      if(cls==2){ unsigned long long gv[64]; int kk=0; for(int i=0;i<k;i++) if(gcdll(pr[i],q)==1) gv[kk++]=sgn(pr[i]%q,q);
        if(inspan(gv,kk,sgn(q-1,q))) cGh++; } }
    if(cls==0) cH++; else if(cls==1) cP++; else if(cls==2) cG++; else cA++;
    int s=0; while((1LL<<(s+1))<=q) s++; byscale[s][cls]++;
  }
  printf("p=%lld Qmax=%lld  slices: hit=%lld prime=%lld charexpl=%lld accidental=%lld\n",p,Qmax,cH,cP,cG,cA);
  printf("  of charexpl: explained only by higher-order (non-quadratic) characters: %lld\n",cGh);
  printf("log2(q)  hit prime char acc\n");
  for(int s=0;s<64;s++) if(byscale[s][0]+byscale[s][1]+byscale[s][2]+byscale[s][3])
    printf("%2d  %lld %lld %lld %lld\n",s,byscale[s][0],byscale[s][1],byscale[s][2],byscale[s][3]);
  return 0;
}
