"""R190 reviewer-2: from-scratch check of the index argument in UNIT_ORBIT_ES Thm 2.4(a) (S = {3,5,7,11}).

(1) For several n = 1 mod 4 (non-squares), build the class a mod M = 4 rad(n) as in the proof (a = 3 mod 4,
    a != 0,1 mod l for l | n, Jacobi (a/n) = -1), list primes r <= X in that class with every prime factor of
    (r-1)/2 >= X^theta, compute the index of Gamma_r = <S> mod r, and for index <= 2 verify r | n + 4Q^2 for an
    explicit Q in <S> (discrete search over exponents).
(2) Lemma 2.3 sanity: #{r <= X : |Gamma_r| <= r^beta}.
Usage: PYTHONPATH=scripts uv run --with sympy python scripts/review_uo2_index.py [X]
"""
import sys
from math import lcm, prod
from sympy import primerange, factorint, n_order, jacobi_symbol

S = [3, 5, 7, 11]
X = int(sys.argv[1]) if len(sys.argv) > 1 else 10**6


def gamma_order(r):
    return lcm(*[n_order(q, r) for q in S])


def find_Q(n, r):
    # Q in <S> with Q^2 = -n/4 mod r; BFS over the group generated by S
    target = (-n * pow(4, -1, r)) % r
    seen = {1: 1}
    frontier = [1]
    while frontier:
        nxt = []
        for g in frontier:
            Qg = seen[g]
            if (g * g - target) % r == 0:
                return Qg
            for q in S:
                h = g * q % r
                if h not in seen:
                    seen[h] = Qg * q
                    nxt.append(h)
        frontier = nxt
    return None


def make_class(n):
    fn = factorint(n)
    odd = [l for l, t in fn.items() if t % 2 == 1 and l >= 5]
    l0 = odd[0]
    res = {}
    for l in fn:
        if l != l0:
            res[l] = 2
    # choose a_{l0} != 0,1 so that Jacobi (a/n) = -1
    for c in range(2, l0):
        res[l0] = c
        sign = prod(jacobi_symbol(res[l], l) ** t for l, t in fn.items())
        if sign == -1:
            break
    # CRT with 3 mod 4
    M, a = 4, 3
    for l, c in res.items():
        a = next(a + M * k for k in range(l) if (a + M * k) % l == c)
        M *= l
    return M, a


theta = 0.2
# (all test n must be = 1 mod 4: the n = 3 mod 4 branch of the proof uses Q = 1 instead)
for n in ([int(t) for t in sys.argv[2:]] or [13, 17, 29, 37, 41, 53, 13 * 17, 13 ** 3, 17 * 19 ** 2, 13 ** 2 * 17 * 29]):
    M, a = make_class(n)
    rs = [r for r in primerange(3, X) if r % M == a and r not in S]
    rough = [r for r in rs if r > 3 and min(factorint((r - 1) // 2)) >= X ** theta]
    idx = [(r - 1) // gamma_order(r) for r in rough]
    good = [r for r, i in zip(rough, idx) if i <= 2]
    for r in good[:200]:
        assert jacobi_symbol(n, r) == -1
        Q = find_Q(n, r)
        assert Q is not None and (n + 4 * Q * Q) % r == 0, (n, r)
    bad = sorted(set(i for i in idx if i > 2))
    print(f"n={n} M={M} a={a}: primes in class {len(rs)}, rough {len(rough)}, index<=2 {len(good)}, "
          f"other indices {bad[:8]}")

for beta in (0.5, 0.75):
    cnt = [r for r in primerange(13, X) if gamma_order(r) <= r ** beta]
    print(f"#{{13<=r<{X}: |Gamma_r| <= r^{beta}}} = {len(cnt)}: {cnt[:15]}")
