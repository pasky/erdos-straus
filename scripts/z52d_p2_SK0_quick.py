# Z0213: is {n = 1 mod 4} multiplicatively closed? (premise check)
S = [n for n in range(1, 2000) if n % 4 == 1]
clos = all((a * b) % 4 == 1 for a in S[:200] for b in S[:200])
print("Z0213 {n≡1 mod 4} multiplicatively closed (check on sample):", clos)
