"""Quick exact checks for SK0 items Z0098, Z0558, Z0265, Z0213, Z0286, Z0208 (pass 2, batch SK0)."""
from fractions import Fraction as F
from math import gcd
from sympy import factorint, totient, primerange

def unit_frac_sum(*xs):
    return sum((F(1, x) for x in xs), F(0))

# Z0098: signed integer ES. For n not a power of 3 pick a prime q|n with q != 3, e = q if q%3==2 else -q
# (so e%3==2, e != -1), s=(e+1)/3, then 4/n = 1/n + 1/(n*s) + 1/(n*s/e).
bad, pos, tot = [], 0, 0
for n in range(2, 10001):
    f = factorint(n)
    if set(f) <= {3}:
        continue
    q = next(p for p in f if p != 3)
    e = q if q % 3 == 2 else -q
    s = (e + 1) // 3
    y, z = n * s, n * s // e
    tot += 1
    assert (n * s) % e == 0
    if unit_frac_sum(n, y, z) != F(4, n) or 0 in (y, z):
        bad.append(n)
    if e > 0 and s > 0:
        pos += 1
print("Z0098 n in [2,1e4] not power of 3:", tot, "identity failures:", bad[:10], "positive-rep via this identity:", pos)
print("Z0098 powers of 3 <=1e4:", [3**k for k in range(0, 10) if 3**k <= 10000])

# Z0558: max density of subgroup H of (Z/4C)^x with -1 not in H  (= 1/min order of a character chi with chi(-1)=-1)
def units(m):
    return [a for a in range(1, m) if gcd(a, m) == 1]
res = {}
for C in range(1, 201):
    m = 4 * C
    G = units(m)
    if m == 4:
        G = [1, 3]
    minus1 = (m - 1) % m
    # brute force: subgroups avoiding -1 generated by a single element: max |<g>|/|G| with -1 not in <g>
    # (max proper subgroups avoiding -1 are maximal cyclic-type; check cyclic subgroups as witnesses plus index-2 existence)
    best = 0.0
    for g in G:
        H = {1}
        x = g
        while x != 1:
            H.add(x); x = x * g % m
        if minus1 not in H:
            best = max(best, len(H) / len(G))
    # index-2 subgroup avoiding -1 exists iff there is a homomorphism G->{±1} with -1 -> -1: the mod-4 character
    chi = lambda a: 1 if a % 4 == 1 else -1
    H2 = [a for a in G if chi(a) == 1]
    assert minus1 not in H2 and len(H2) * 2 == len(G)
    res[C] = max(best, len(H2) / len(G))
vals = set(res.values())
print("Z0558 max density of H avoiding -1 over C<=200: values", sorted(vals))
print("Z0558 C where max density < 1/2 (should be none):", [C for C, v in res.items() if v < 0.5][:5])

# Z0265: ES over Z_(p) with denominators in Z_(p) (odd p): 4/n = 1/(n/2) + 1/n + 1/n
