#!/usr/bin/env python3
"""z66 HSTARF: brute-force check of the abelian realisation problem.
For n in argv, search 2-generated abelian groups G = Z_m x Z_k (m | k), |G| <= BOUND, and generating pairs (g1,g2)
with signature (x,y,z) = (ord g1, ord g2, ord(g1+g2)) satisfying 1/x+1/y+1/z = 4/n.
Such a pair <=> a Riemann surface X = H/ker(Delta(x,y,z) -> G) with G acting, X/G = P^1 with 3 branch points and
|G|(n-4) = n(2g-2)  (Riemann-Hurwitz).  Reports signatures found, the pattern of n-divisibility, and whether the
Sylow-type condition "G = Z_n x A, gcd(|A|,n)=1, Z_n in stab of two branch points, Z_n meets third stab trivially" holds.
usage: uv run scripts/z66_hstarf_abelian.py BOUND n1 n2 ...
"""
import sys
from math import gcd
from fractions import Fraction
from itertools import product
from sympy import divisors, factorint

def order(g, m, k):
    a, b = g
    oa = m // gcd(a, m); ob = k // gcd(b, k)
    return oa * ob // gcd(oa, ob)

def generates(g1, g2, m, k):
    # subgroup generated by g1,g2 in Z_m x Z_k has full order?
    # compute via Smith-like: size of lattice spanned by g1,g2,(m,0),(0,k) in Z^2 -> index = |det| gcd of 2x2 minors
    rows = [g1, g2, (m, 0), (0, k)]
    g = 0
    for i in range(4):
        for j in range(i + 1, 4):
            g = gcd(g, rows[i][0] * rows[j][1] - rows[i][1] * rows[j][0])
    return abs(g) == 1  # index of lattice in Z^2 is gcd of minors ... actually index = gcd of 2x2 minors; full group iff == 1

def main():
    bound = int(sys.argv[1]); ns = [int(a) for a in sys.argv[2:]]
    for n in ns:
        found = {}
        for N in range(n, bound + 1, n):  # |G| must be divisible by n (n | exp(G) needed since 4/n has denominator n)
            if (N * (n - 4)) % n: continue  # 2g-2 = |G|(n-4)/n must be an integer
            for m in divisors(N):
                k = N // m
                if k % m: continue
                seen = set()
                for g1 in product(range(m), range(k)):
                    x = order(g1, m, k)
                    if x == 1: continue
                    for g2 in product(range(m), range(k)):
                        y = order(g2, m, k)
                        if y == 1 or y < x: continue
                        z = order(((g1[0] + g2[0]) % m, (g1[1] + g2[1]) % k), m, k)
                        if z == 1: continue
                        if Fraction(1, x) + Fraction(1, y) + Fraction(1, z) != Fraction(4, n): continue
                        if not generates(g1, g2, m, k): continue
                        sig = tuple(sorted((x, y, z)))
                        key = (m, k, sig)
                        if key in seen: continue
                        seen.add(key)
                        pat = tuple(sorted(gcd(v, n) for v in sig))
                        found.setdefault(sig, []).append((m, k, pat))
        print(f"n={n} bound={bound}: {len(found)} signatures")
        for sig, lst in sorted(found.items()):
            groups = sorted(set((m, k) for m, k, _ in lst))
            pat = lst[0][2]
            print(f"   sig={sig} gcds-with-n={pat} groups(Z_m x Z_k)={groups[:4]}{'...' if len(groups)>4 else ''}")

main()
