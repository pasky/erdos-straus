"""R183 from-scratch test of T1_TEMPLATE Thm 2.1 (local invariants of alpha(u) = (-u1/u3, -u2/u3) on integral
points of 4/n = 1/u1 + 1/u2 + 1/u3) over Q(sqrt5), Q(sqrt2), Q(sqrt3), Q(cbrt2).  Own arithmetic in Z[t]/(f),
own tame symbols at every odd place (unramified via Hensel-lifted factors of f, ramified via an explicit
uniformiser), own 2-adic Hilbert symbol (K_v^*/K_v^*2 computed explicitly, norm groups N(K_v(sqrt a)) generated by
sampling x^2 - a y^2; index 2 is checked), real symbols from signs.  Does NOT use the author's code.

Checks on every solution: (a) real formula; (b) 0 at odd v not dividing n; (c) 0 at the place above 2;
(d) 0 at v | n with v(n) even and Type I / Type II shape at v; and the full reciprocity sum = 0
(a consistency check of all the local code, since inv_2 is computed DIRECTLY, not by reciprocity).
Usage: PYTHONPATH=scripts uv run --with sympy python scripts/review_t1t_local.py [B] [maxsol]
"""
import sys, random, itertools
from fractions import Fraction
from sympy import factorint, Poly, symbols, factor_list, divisors
import mpmath, warnings
warnings.filterwarnings('ignore')
mpmath.mp.dps = 80
X = symbols('X')

class Field:
    def __init__(s, name, f, pi2, e2, f2, ram):
        # f: list of coefficients c_0..c_{d-1} with t^d = sum c_i t^i  (monic, O = Z[t] maximal)
        s.name, s.c, s.d = name, f, len(f)
        s.pi2, s.e2, s.f2 = pi2, e2, f2           # uniformiser above 2, ramification, residue degree
        s.ram = ram                                # odd ramified l -> (uniformiser, multiple root mod l)
        poly = [1] + [-ci for ci in reversed(f)]   # leading first
        s.fpoly = Poly(poly, X)
        s.reals = [r for r in mpmath.polyroots(poly, maxsteps=200, extraprec=200) if abs(mpmath.im(r)) < mpmath.mpf(10) ** -60]
        s.reals = [mpmath.re(r) for r in s.reals]
    def mul(s, a, b):
        d = s.d; prod = [0] * (2 * d - 1)
        for i, ai in enumerate(a):
            if ai:
                for j, bj in enumerate(b): prod[i + j] += ai * bj
        for k in range(2 * d - 2, d - 1, -1):
            ck = prod[k]
            if ck:
                prod[k] = 0
                for i, ci in enumerate(s.c): prod[k - d + i] += ck * ci
        return tuple(prod[:d])
    def add(s, a, b): return tuple(x + y for x, y in zip(a, b))
    def sc(s, k, a): return tuple(k * x for x in a)
    def one(s): return tuple([1] + [0] * (s.d - 1))
    def num(s, k): return tuple([k] + [0] * (s.d - 1))
    def mat(s, a):
        cols = []; e = s.one()
        for i in range(s.d):
            basis = tuple(1 if j == i else 0 for j in range(s.d))
            cols.append(s.mul(a, basis))
        return [[cols[j][i] for j in range(s.d)] for i in range(s.d)]
    def norm(s, a):
        M = [[Fraction(x) for x in row] for row in s.mat(a)]
        return int(det(M))
    def div(s, a, b):
        """exact a/b in K as Fraction vector"""
        M = [[Fraction(x) for x in row] for row in s.mat(b)]
        return solve(M, [Fraction(x) for x in a])
    def exdiv(s, a, b):
        q = s.div(a, b)
        if all(x.denominator == 1 for x in q): return tuple(int(x) for x in q)
        return None
    def real_sign(s, a, r):
        v = sum(mpmath.mpf(ai) * r ** i for i, ai in enumerate(a))
        assert abs(v) > mpmath.mpf(10) ** -50
        return 1 if v > 0 else -1

def det(M):
    M = [row[:] for row in M]; n = len(M); dt = Fraction(1)
    for i in range(n):
        p = next((r for r in range(i, n) if M[r][i] != 0), None)
        if p is None: return Fraction(0)
        if p != i: M[i], M[p] = M[p], M[i]; dt = -dt
        dt *= M[i][i]
        for r in range(i + 1, n):
            fct = M[r][i] / M[i][i]
            for c in range(i, n): M[r][c] -= fct * M[i][c]
    return dt

def solve(M, v):
    n = len(M); A = [M[i][:] + [v[i]] for i in range(n)]
    for i in range(n):
        p = next(r for r in range(i, n) if A[r][i] != 0)
        A[i], A[p] = A[p], A[i]
        for r in range(n):
            if r != i and A[r][i] != 0:
                fct = A[r][i] / A[i][i]
                for c in range(i, n + 1): A[r][c] -= fct * A[i][c]
    return [A[i][n] / A[i][i] for i in range(n)]

def vl(x, l):
    if x == 0: return 10 ** 9
    v = 0
    while x % l == 0: x //= l; v += 1
    return v

# ---------- polynomial helpers mod m (coefficient lists, low degree first) ----------
def pmod(a, g, m):
    """a mod monic g over Z/m"""
    a = [x % m for x in a]; dg = len(g) - 1
    for k in range(len(a) - 1, dg - 1, -1):
        ck = a[k]
        if ck:
            for i in range(dg + 1): a[k - dg + i] = (a[k - dg + i] - ck * g[i]) % m
    return a[:dg] + [0] * max(0, dg - len(a))

def pmulmod(a, b, g, m):
    prod = [0] * (len(a) + len(b) - 1)
    for i, x in enumerate(a):
        for j, y in enumerate(b): prod[i + j] += x * y
    return pmod(prod, g, m)

def ppow(a, e, g, m):
    r = [1] + [0] * (len(g) - 2); b = a
    while e:
        if e & 1: r = pmulmod(r, b, g, m)
        b = pmulmod(b, b, g, m); e >>= 1
    return r

def pinv(a, g, l):
    q = l ** (len(g) - 1)
    return ppow(a, q - 2, g, l)

def is_square_res(u, g, l):
    q = l ** (len(g) - 1)
    r = ppow(u, (q - 1) // 2, g, l)
    one = [1] + [0] * (len(g) - 2)
    assert r == one or r == [(-1) % l] + [0] * (len(g) - 2)
    return r == one

# ---------- odd places ----------
PREC = 60
def odd_places(F, l):
    """list of (kind, data) for the primes above odd l"""
    if l in F.ram:
        return [('ram', F.ram[l])]
    fl = [(-c) % l for c in F.c] + [1]   # f low-first
    _, facs = factor_list(F.fpoly, modulus=l)
    out = []
    m = l ** PREC
    for fac, mult in facs:
        assert mult == 1
        co = [int(x) % l for x in reversed(Poly(fac, X).all_coeffs())]   # low-first, monic
        if len(co) == 2:
            r = (-co[0]) % l
            # Newton lift
            fpoly = lambda x: (pow(x, F.d, m) - sum(c * pow(x, i, m) for i, c in enumerate(F.c))) % m
            fder = lambda x: (F.d * pow(x, F.d - 1, m) - sum(i * c * pow(x, i - 1, m) for i, c in enumerate(F.c) if i)) % m
            for _ in range(8): r = (r - fpoly(r) * pow(fder(r), -1, m)) % m
            assert fpoly(r) == 0
            out.append(('unr', [(-r) % m, 1]))
        else:
            out.append(('deg', len(co) - 1, co))
    # lift higher-degree factor: f / prod(linear lifted) (at most one non-linear factor in our fields)
    fin = []
    lins = [o[1] for o in out if o[0] == 'unr']
    nonlin = [o for o in out if o[0] == 'deg']
    assert len(nonlin) <= 1
    for g in lins: fin.append(('unr', g))
    if nonlin:
        full = [(-c) % m for c in F.c] + [1]
        for g in lins:   # divide by (x - r)
            r = (-g[0]) % m
            D = len(full) - 1
            q = [0] * D
            q[D - 1] = full[D] % m
            for k in range(D - 1, 0, -1): q[k - 1] = (full[k] + r * q[k]) % m
            assert (full[0] + r * q[0]) % m == 0
            full = q
        assert len(full) - 1 == nonlin[0][1]
        fin.append(('unr', full))
    return fin

def odd_val_res(F, a, place, l):
    kind, data = place
    if kind == 'unr':
        g = data; m = l ** PREC
        r = pmod(list(a), g, m)
        v = min(vl(x, l) for x in r)
        assert v < PREC - 5
        u = [(x // l ** v) % l for x in r]
        gl = [x % l for x in g]
        return v, u, gl
    pi, r0 = data
    N = abs(F.norm(a)); v = vl(N, l)
    cur = a
    for _ in range(v): cur = F.exdiv(cur, pi); assert cur is not None
    u = sum(c * pow(r0, i, l) for i, c in enumerate(cur)) % l
    assert u != 0
    return v, [u], [(-r0) % l, 1]

def tame_inv(F, a, b, place, l):
    va, ua, g = odd_val_res(F, a, place, l)
    vb, ub, _ = odd_val_res(F, b, place, l)
    t = pmulmod(ppow(ua, vb, g, l), ppow(pinv(ub, g, l), va, g, l), g, l)
    if (va * vb) % 2: t = [(-x) % l for x in t]
    return 0 if is_square_res(t, g, l) else 1   # in units of 1/2

def place_val_n(F, n, place, l):
    return odd_val_res(F, F.num(n), place, l)[0]

# ---------- the place above 2 ----------
class TwoAdic:
    def __init__(s, F, seed=1):
        s.F = F; e = F.e2; s.M = 8   # work mod 8 = pi^{3e} which is inside pi^{2e+1}
        d = F.d
        elems = list(itertools.product(range(8), repeat=d))
        unit = lambda a: F.norm(a) % 2 == 1
        s.units = [a for a in elems if unit(a)]
        red = lambda a: tuple(x % 8 for x in a)
        pw = F.one()
        for _ in range(2 * e + 1): pw = F.mul(pw, F.pi2)
        H = set(red(F.mul(w, w)) for w in s.units)
        H |= set(red(F.add(F.one(), F.mul(pw, t))) for t in elems)
        # close under multiplication
        H = set(H); changed = True
        while changed:
            changed = False
            for h1 in list(H):
                for h2 in list(H):
                    p = red(F.mul(h1, h2))
                    if p not in H: H.add(p); changed = True
            if len(H) > len(s.units): raise RuntimeError
        s.H = H
        ncls = len(s.units) // len(H)
        assert ncls == 2 ** (1 + d), (F.name, ncls)   # |U/U^2| = 2^{1+[K_v:Q_2]}
        s.ucls = {}
        reps = []
        order = [tuple(x % 8 for x in F.one())] + [u for u in s.units if u != tuple(x % 8 for x in F.one())]
        for u in order:
            if u in s.ucls: continue
            idx = len(reps); reps.append(u)
            for h in H: s.ucls[red(F.mul(u, h))] = idx
        s.nclass = 2 * ncls
        s.rng = random.Random(seed)
        s.table = {}
    def cls(s, a):
        F = s.F
        N = F.norm(a); v = vl(abs(N), 2); assert v % F.f2 == 0; v //= F.f2
        cur = a
        for _ in range(v): cur = F.exdiv(cur, F.pi2); assert cur is not None
        return (v % 2, s.ucls[tuple(x % 8 for x in cur)])
    def normgroup(s, ca, a):
        F = s.F; G = set([(0, 0)]); target = s.nclass // 2
        mulc = lambda c1, c2: s.mulcls(c1, c2)
        tries = 0
        while len(G) < target:
            tries += 1; assert tries < 20000, 'norm group not generated'
            x = tuple(s.rng.randint(-12, 12) for _ in range(F.d))
            y = tuple(s.rng.randint(-12, 12) for _ in range(F.d))
            w = F.add(F.mul(x, x), F.sc(-1, F.mul(a, F.mul(y, y))))
            if all(c == 0 for c in w): continue
            c = s.cls(w)
            if c not in G:
                G = s.closure(G | {c})
                assert len(G) <= target, 'norm group larger than index 2'
        return G
    def mulcls(s, c1, c2):
        return ((c1[0] + c2[0]) % 2, s.umul[(c1[1], c2[1])])
    def closure(s, G):
        G = set(G); changed = True
        while changed:
            changed = False
            for a in list(G):
                for b in list(G):
                    c = s.mulcls(a, b)
                    if c not in G: G.add(c); changed = True
        return G
    def prepare(s):
        F = s.F
        reps = {}
        for u, i in s.ucls.items(): reps.setdefault(i, u)
        s.urep = reps
        s.umul = {(i, j): s.ucls[tuple(x % 8 for x in F.mul(reps[i], reps[j]))] for i in reps for j in reps}
        # representatives of all classes as elements of O
        s.crep = {}
        for par in (0, 1):
            for i, u in reps.items():
                s.crep[(par, i)] = F.mul(u, F.pi2) if par else u
        for ca, a in s.crep.items():
            if ca == (0, 0):
                s.table[ca] = set(s.crep); continue
            s.table[ca] = s.normgroup(ca, a)
        # sanity: symmetric pairing
        for ca in s.crep:
            for cb in s.crep:
                assert (cb in s.table[ca]) == (ca in s.table[cb]), 'asymmetric Hilbert pairing'
    def inv(s, a, b):
        return 0 if s.cls(b) in s.table[s.cls(a)] else 1

def hilbert2_Q(a, b):
    """classical (a,b)_2 for nonzero rationals given as integers; 0 or 1"""
    al, bl = vl(abs(a), 2), vl(abs(b), 2); u, w = a >> al if a > 0 else -((-a) >> al), b >> bl if b > 0 else -((-b) >> bl)
    eps = lambda x: ((x - 1) // 2) % 2
    om = lambda x: ((x * x - 1) // 8) % 2
    return (eps(u) * eps(w) + al * om(w) + bl * om(u)) % 2

# ---------- fields ----------
def fields():
    return [
        Field('Q(sqrt5)', [1, 1], (2, 0), 1, 2, {5: ((-1, 2), 3)}),
        Field('Q(sqrt2)', [2, 0], (0, 1), 2, 1, {}),
        Field('Q(sqrt3)', [3, 0], (1, 1), 2, 1, {3: ((0, 1), 0)}),
        Field('Q(cbrt2)', [2, 0, 0], (0, 1, 0), 3, 1, {3: ((1, 1, 0), 2)}),
    ]
UNIT = {'Q(sqrt5)': (0, 1), 'Q(sqrt2)': (1, 1), 'Q(sqrt3)': (2, 1), 'Q(cbrt2)': (-1, 1, 0)}

def gen_solutions(F, n, B, J, maxsol, rng):
    sols = set()
    eps = UNIT[F.name]
    epsinv = F.exdiv(F.one(), eps)
    units = []
    for j in range(-J, J + 1):
        u = F.one()
        for _ in range(abs(j)): u = F.mul(u, eps if j > 0 else epsinv)
        units += [u, F.sc(-1, u)]
    box = list(itertools.product(range(-B, B + 1), repeat=F.d))
    rng.shuffle(box)
    for x in box:
        if all(c == 0 for c in x): continue
        A = F.add(F.sc(4, x), F.num(-n))
        if all(c == 0 for c in A): continue
        Bv = F.sc(n, x); B2 = F.mul(Bv, Bv)
        Ds = []
        for dd in divisors(n * n):
            for i in range(3):
                xi = F.one()
                for _ in range(i): xi = F.mul(xi, x)
                for u in units: Ds.append(F.mul(F.sc(dd, xi), u))
        for D in Ds:
            u2 = F.exdiv(F.add(Bv, D), A)
            if u2 is None or all(c == 0 for c in u2): continue
            D2 = F.exdiv(B2, D)
            if D2 is None: continue
            u3 = F.exdiv(F.add(Bv, D2), A)
            if u3 is None or all(c == 0 for c in u3): continue
            lhs = F.sc(4, F.mul(x, F.mul(u2, u3)))
            rhs = F.sc(n, F.add(F.add(F.mul(x, u2), F.mul(u2, u3)), F.mul(u3, x)))
            assert lhs == rhs
            sols.add((x, u2, u3))
            if len(sols) >= maxsol: return list(sols)
    return list(sols)

def check_field(F, ns, B, J, maxsol):
    rng = random.Random(7)
    T = TwoAdic(F); T.prepare()
    # validate 2-adic code on rational pairs: inv_v(a,b)_K = [K_v:Q_2] * (a,b)_2
    for _ in range(300):
        a = rng.choice([-1, 1]) * rng.randint(1, 400); b = rng.choice([-1, 1]) * rng.randint(1, 400)
        assert T.inv(F.num(a), F.num(b)) == (F.d * hilbert2_Q(a, b)) % 2, (F.name, a, b)
    # nontrivial test of the 2-adic symbol: reciprocity on random pairs a, b in O
    nz2 = 0
    for _ in range(150):
        a = tuple(rng.randint(-9, 9) for _ in range(F.d)); b = tuple(rng.randint(-9, 9) for _ in range(F.d))
        if F.norm(a) == 0 or F.norm(b) == 0: continue
        tot = T.inv(a, b); nz2 += T.inv(a, b)
        for r in F.reals: tot += 1 if (F.real_sign(a, r) < 0 and F.real_sign(b, r) < 0) else 0
        for l in set(factorint(abs(F.norm(a)))) | set(factorint(abs(F.norm(b)))):
            if l == 2: continue
            for pl in odd_places(F, l): tot += tame_inv(F, a, b, pl, l)
        assert tot % 2 == 0, ('reciprocity fails on random pair', F.name, a, b)
    print(F.name, 'random-pair reciprocity OK; inv_2 nonzero on', nz2, 'of 150 random pairs', flush=True)
    stats = dict(sols=0, two_nonzero=0, tame_nonzero_off_n=0, real_mismatch=0, d_nonzero=0, d_cases=0,
                 recip_fail=0, two_cases={})
    for n in ns:
        sols = gen_solutions(F, n, B, J, maxsol, rng)
        for u in sols:
            stats['sols'] += 1
            u1, u2, u3 = u
            a = F.sc(-1, F.mul(u1, u3)); b = F.sc(-1, F.mul(u2, u3))   # (-u1/u3,-u2/u3) = (-u1u3,-u2u3)
            total = 0
            for r in F.reals:
                sa, sb = F.real_sign(a, r), F.real_sign(b, r)
                iv = 1 if (sa < 0 and sb < 0) else 0
                same = len({F.real_sign(ui, r) for ui in u}) == 1
                if iv != (1 if same else 0): stats['real_mismatch'] += 1
                total += iv
            i2 = T.inv(a, b)
            if i2: stats['two_nonzero'] += 1
            vs = tuple(T.cls(ui)[0] for ui in u)   # valuation parities only; record whether some u_i non-unit at 2
            key = 'some u_i non-unit' if any(F.norm(ui) % 2 == 0 for ui in u) else 'all units'
            stats['two_cases'][key] = stats['two_cases'].get(key, 0) + 1
            total += i2
            ls = set(factorint(abs(F.norm(a)))) | set(factorint(abs(F.norm(b)))) | set(factorint(n))
            for l in ls:
                if l == 2: continue
                for pl in odd_places(F, l):
                    iv = tame_inv(F, a, b, pl, l)
                    total += iv
                    vn = place_val_n(F, n, pl, l)
                    if vn == 0 and iv: stats['tame_nonzero_off_n'] += 1
                    if vn > 0 and vn % 2 == 0:
                        vals = [odd_val_res(F, ui, pl, l)[0] for ui in u]
                        nunit = sum(1 for x in vals if x == 0)
                        big = sum(1 for x in vals if x >= vn)
                        if (nunit == 2 and big == 1) or (nunit == 1 and big == 2):
                            stats['d_cases'] += 1
                            if iv: stats['d_nonzero'] += 1
            if total % 2: stats['recip_fail'] += 1
    # control (teeth): even n, where Thm 2.1(c) does not apply -- inv_2 should be non-zero sometimes
    ctrl = 0; ctot = 0
    for n in (2, 6, 10, 18):
        for u in gen_solutions(F, n, B, J, maxsol // 2, rng):
            u1, u2, u3 = u
            ctot += 1; ctrl += T.inv(F.sc(-1, F.mul(u1, u3)), F.sc(-1, F.mul(u2, u3)))
    stats['control_even_n_inv2_nonzero'] = f"{ctrl}/{ctot}"
    return stats

