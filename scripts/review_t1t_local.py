    B = int(sys.argv[1]) if len(sys.argv) > 1 else 3
    maxsol = int(sys.argv[2]) if len(sys.argv) > 2 else 150
    ns = [3, 7, 9, 11, 13, 15, 21, 25, 29, 45, 49, 81, 121, 169, 225]
