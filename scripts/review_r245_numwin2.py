"""R245: odd nu forces K even (m = nu*K - n odd). Correct 2-adic forcing (CAP_DOWN Thm 1.2 style): K = 2^t K', K' odd,
every prime q | m is 3 mod 4 with (K'/q) = -1. Then Q^2 = -K' (mod m), Q in <odd primes of K'>, d = 2^t Q^2 = -K (mod m),
Lemma 1.1 (nu version): x = K, A = (K+d)/m, y = nA, z = nKA/d.  Search odd squares n = a^2, build and VERIFY the solution."""
import sys
from fractions import Fraction as F
from sympy import factorint, legendre_symbol
from math import gcd
from itertools import product
def build(nu, n, K, m):
    t = (K & -K).bit_length() - 1; Kp = K >> t
    S = list(factorint(Kp))
    # BFS in the subgroup generated by S mod m for an element h with h^2 = -Kp, keep exponent vector
    target = (-Kp) % m
    seen = {1: ()}; frontier = [1]; vec = {1: {}}
    while frontier:
        nf = []
        for g in frontier:
            for s in S:
                h = g * s % m
                if h not in vec:
                    v = dict(vec[g]); v[s] = v.get(s, 0) + 1; vec[h] = v; nf.append(h)
        frontier = nf
    for h, v in vec.items():
        if h * h % m == target:
            Q = 1
            for s, e in v.items(): Q *= s**e
            d = 2**t * Q * Q
            assert (K + d) % m == 0
            A = (K + d) // m; x, y, z = K, n * A, F(n * K * A, d)
            assert F(nu, n) == F(1, x) + F(1, y) + 1 / z
            D = z.denominator; assert gcd(D, 2 * n) == 1 and all(y % q == 0 for q in factorint(D))  # ES^(y,e): odd, prime to n, rad | y
            return x, y, z
    return None
NUS = [int(v) for v in sys.argv[3].split(',')]
A, MW = int(sys.argv[1]), int(sys.argv[2])
for nu in NUS:
    hit = tot = 0; ex = None
    for a in range(3, A, 2):
        if gcd(a, nu) != 1: continue
        tot += 1; n = a * a
        for K in range(n // nu + 1, (n + MW) // nu + 1):
            m = nu * K - n
            if m <= 1 or m % 2 == 0 or gcd(m, n) != 1 or gcd(K, n) != 1: continue
            Kp = K >> ((K & -K).bit_length() - 1)
            f = factorint(m)
            if all(q % 4 == 3 and legendre_symbol(Kp % q, q) == -1 for q in f):
                sol = build(nu, n, K, m); assert sol
                hit += 1; ex = ex or (a, K, m, sol); break
    print(f'nu={nu}: squares with corrected forced window {hit}/{tot}; example {ex}')
