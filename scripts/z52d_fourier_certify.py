"""Independent check (sympy, no Fourier code) of the Theorem B counterexamples to the bounded-order inverse lemma:
forced prime windows q ≡ 3 (4), (q−1)/2 prime, box misses −1, ⟨prime factors of N⟩ = (Z/q)^*."""
from itertools import product
from fractions import Fraction
from sympy import factorint, isprime, legendre_symbol, n_order
for p, q in [(1005913, 587), (5211721, 479), (1714441, 503), (102001, 1907), (103681, 1619), (101161, 1523), (1249, 59), (31121, 43)]:
    assert isprime(p) and isprime(q) and q % 4 == 3 and p % 4 == 1
    N = (p + q) // 4; f = factorint(N)
    forced = legendre_symbol(q, p) == -1
    box = set()
    for d in product(*[range(-b, b + 1) for b in f.values()]):
        v = 1
        for s, k in zip(f, d):
            v = v * pow(s, k, q) % q
        box.add(v)
    hits = (q - 1) in box
    # generated subgroup = whole group iff gcd of orders... compute via lcm-closure: subgroup of cyclic group generated by
    # elements of orders o_i has order lcm(o_i)
    from math import lcm
    H = 1
    for s in f: H = lcm(H, n_order(s % q, q))
    from math import prod
    cbm = legendre_symbol(q % p, p) * prod(Fraction(1, 2 * b + 1) for s, b in f.items() if legendre_symbol(s % p, p) == -1)
    print(p, q, 'N =', N, f, 'Prop1 c(chi_-q) =', cbm, 'forced', forced, '(q-1)/2 prime', isprime((q - 1) // 2), 'box hits -1:', hits,
          '|H| =', H, 'of', q - 1, '| box size', len(box))
