"""review_r241_cert.py (R241): independent re-summation of the FF_ODD_ABSENCE Thm 2.2 certificate (q = 9, k = 1, slices P8).
Inputs:
  * per-pattern route bounds from R226's reviewer code review_fz1_sum.c (R226_DUMP=s; lines 'P s a z y t bound route';
    written from the text of (J)56, NOT the author's fz1_sum.c), generated by the shell loop in the review;
  * exact P8 counts: R241's own enumeration (review_r241_enum.py output files) for s in EXACT_MINE, and the author's
    data/zc/p_20.txt for s = 20 (the only input not reproduced; SKIP lines -> R226 route bound);
  * tail s > 80 and Case A: numbers passed on the command line.
Filters (re-derived in the review): 4 | s, eps(s; z, t) = (-1)^{t + tz + z(1+s) + ts} must equal (-1)^{s/4}.
Mass per ordered tuple 9^{-ceil((s-1)/2)}; route bounds are for a <= b and get mult 2 if a < b.
usage: review_r241_cert.py r226_bounds enum_out[,enum_out...] p20file tail caseA"""
import sys
from fractions import Fraction as Fr
q = 9
bfile, enums, p20, tail, caseA = sys.argv[1], sys.argv[2].split(','), sys.argv[3], float(sys.argv[4]), float(sys.argv[5])
def eps(s, z, t):
    return -1 if (t + t * z + z * (1 + s) + t * s) % 2 else 1
def compatible(s, z, t):
    return s % 4 == 0 and eps(s, z, t) == (-1) ** (s // 4)
BND = {}
for l in open(bfile):
    f = l.split()
    s, a, z, y, t = map(int, f[1:6]); BND[(s, a, z, y, t)] = float(f[6])
# exact (mine): ordered tuples with E0 in P8 (odd log), summed over all patterns of level s
exact = {}
for fn in enums:
    for l in open(fn):
        if not l.startswith('P '):
            continue
        f = l.split(); s, a, b, z, y, t = map(int, f[1:7])
        c = sum(int(v) for k, v in (x.split(':') for x in f[7:]) if int(k) % 2 == 1)
        if c and not compatible(s, z, t):
            sys.exit(f'P8 tuple in incompatible pattern {(s, a, b, z, y, t)}: law/filter violated')
        exact[s] = exact.get(s, 0) + c
total = 0.0; parts = []
for s in sorted(exact):
    m = Fr(exact[s], q ** (s // 2)); total += float(m); parts.append((s, 'mine-exact', float(m)))
# s = 20: author's exact counts, SKIP -> R226 bound
s = 20; ex20 = 0; sk20 = 0.0; nl = 0; seen = set()
for l in open(p20):
    f = l.split()
    ss, a, z, y, t = map(int, f[:5]); b = ss - a - z
    assert ss == 20 and t == b - y and a <= b and (a, z, y) not in seen; seen.add((a, z, y)); nl += 1
    assert compatible(ss, z, t)
    mult = 2 if a < b else 1
    if f[5] == 'SKIP':
        sk20 += mult * BND[(20, a, z, y, t)] / q ** 10
    else:
        ex20 += mult * int(f[5]) / q ** 10
ncomp20 = sum(1 for (ss, a, z, y, t) in BND if ss == 20 and compatible(20, z, t))
assert nl == ncomp20, (nl, ncomp20)
total += ex20 + sk20; parts.append((20, 'author-exact', ex20)); parts.append((20, 'skip->R226 bound', sk20))
rb = 0.0
for s in range(24, 81, 4):
    acc = 0.0
    for (ss, a, z, y, t), bd in BND.items():
        if ss != s or not compatible(s, z, t):
            continue
        b = s - a - z; acc += (2 if a < b else 1) * bd / q ** (s // 2)
    rb += acc
total += rb; parts.append(('24..80', 'R226 bounds', rb))
for p in parts:
    print(*p)
cert = 1.01 * (total + tail + caseA)
print(f'caseB(s<=80)={total:.8f} tail={tail} caseA={caseA} certified x1.01 = {cert:.6f} < 4: {cert < 4}')
