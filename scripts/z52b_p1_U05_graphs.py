"""z52b pass1 U05 graph items (F_p per FOREST_CONNECTIVITY.md: vertices 1..p+2, u<v adjacent iff uv | p+u+v).
Z2792: index of <uv : edge (u,v)> in F_p^*; Z2840: Molloy–Reed ratio and giant component of F_p;
Z2678: Hoffman bound on independence number from the spectrum of F_p vs. actual max-QR-class constraint;
Z2681: dimension of F2 colourings c on vertices 1..p+2 with c constant on forest edges and c(ku)=c(u)+c(k), k∈{2,3,5}
(c(k) free variables), via GF(2) elimination with Python-int bitsets."""
import numpy as np
from collections import Counter
out = []
def log(*a):
    s = " ".join(str(x) for x in a); print(s); out.append(s)
M = 6000
isp = [True]*(M+1); isp[0] = isp[1] = False
for i in range(2, int(M**.5)+1):
    if isp[i]:
        for j in range(i*i, M+1, i): isp[j] = False
PR = [p for p in range(5, M) if isp[p] and p % 4 == 1]
def leg(a, p):
    a %= p; return 0 if a == 0 else (1 if pow(a, (p-1)//2, p) == 1 else -1)
def forest(p):
    V = p + 2; E = []
    for u in range(1, V+1):
        for v in range(u+1, V+1):
            if (p + u + v) % (u*v) == 0: E.append((u, v))
            if u >= 2 and u*(v+1) > p + u + v + 1 and v > u: break
    return V, E
def rank_gf2(rows):
    piv = {}
    r = 0
    for x in rows:
        while x:
            h = x.bit_length() - 1
            if h in piv: x ^= piv[h]
            else: piv[h] = x; r += 1; break
    return r
gen1 = 0; ntot = 0; mr = []; giant = []; flat = Counter(); hb = []
for p in PR:
    if p > 2500: break
    V, E = forest(p)
    ntot += 1
    prods = set((u*v) % p for u, v in E if u < p and v < p and (u*v) % p)
    H = {1}; fr = [1]
    while fr:
        x = fr.pop()
        for g in prods:
            y = x*g % p
            if y not in H: H.add(y); fr.append(y)
    gen1 += (len(H) == p-1)
    deg = Counter()
    for u, v in E: deg[u] += 1; deg[v] += 1
    d = np.array([deg[x] for x in range(1, V+1)], float)
    mr.append((d*(d-2)).sum()/d.sum())
    par = list(range(V+1))
    def f_(x):
        while par[x] != x: par[x] = par[par[x]]; x = par[x]
        return x
    for u, v in E: par[f_(u)] = f_(v)
    cnt = Counter(f_(x) for x in range(1, V+1))
    giant.append(cnt[f_(1)]/V)
    # Z2681 GF(2) system over variables c_1..c_V (bit i-1), constraints as bitmasks
    rows = []
    for u, v in E: rows.append((1 << (u-1)) ^ (1 << (v-1)))
    for k in (2, 3, 5):
        if k > V: continue
        for u in range(1, V//k + 1):
            rows.append((1 << (k*u-1)) ^ (1 << (u-1)) ^ (1 << (k-1)))
    rk = rank_gf2(rows)
    flat[V - rk] += 0
    # Legendre colouring (as bit vector) satisfies the system iff no bichromatic forest edge (multiplicativity holds)
    leg_bad = sum(1 for u, v in E if leg(u, p) != leg(v, p))
    hb.append(leg_bad)
    flat[('dim', min(V - rk, 3))] += 1
    flat[('legendre_is_solution', leg_bad == 0)] += 1
log(f"Z2792: subgroup generated by edge products uv is all of F_p^* for {gen1} of {ntot} primes p≡1(4), p≤2500")
log(f"Z2840: Molloy–Reed Σd(d−2)/Σd over p≤2500: median {np.median(mr):.2f} (range {min(mr):.2f}–{max(mr):.2f}); giant-comp(1) fraction median {np.median(giant):.3f}, min {min(giant):.3f}")
log(f"Z2681: F2 solution-space dimension (c on vertices, constancy on forest edges, multiplicativity for k=2,3,5): {dict((k[1],v) for k,v in flat.items() if isinstance(k,tuple) and k[0]=='dim')}")
log(f"  Legendre colouring is a solution (⇔ no bichromatic edge) for {flat[('legendre_is_solution', True)]} of {ntot} primes")
# Z2678 spectrum: Hoffman bound for independence number of F_p vs. p+2 (p≤1200)
hb2 = []
for p in [q for q in PR if q <= 1200]:
    V, E = forest(p)
    A = np.zeros((V, V))
    for u, v in E: A[u-1, v-1] = A[v-1, u-1] = 1
    lam = np.linalg.eigvalsh(A)
    lmax, lmin = lam[-1], lam[0]
    hof = V*(-lmin)/(lmax - lmin) if lmax > lmin else float('nan')
    hb2.append((p, round(lmax, 3), round(lmin, 3), round(hof/V, 3)))
log("Z2678 F_p spectrum (p≡1(4), p≤1200): λmax, λmin, Hoffman α/V (first 5):", hb2[:5])
log(f"  Hoffman α/V over these primes: min {min(h[3] for h in hb2):.3f}, median {np.median([h[3] for h in hb2]):.3f}; QR class has density 1/2 (Hoffman is not below 1/2 for the largest class)")
open("data/z52b/pass1/U05/2nd/graphs_out.txt", "w").write("\n".join(out)+"\n")
