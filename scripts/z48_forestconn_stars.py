"""z48 forestconn: depth-1 stars at the 'quadratic-layer' roots u in {1,2,3,4,6} (phi(u) <= 2).

star(u) certifies  <=>  some child v>u of u (v | p+u, v == -p mod u) has chi(v) != chi(u).
Children are computed from sympy divisors and colours from sympy Legendre symbols (independent
of the C scanner).  We also test the closed-form multiplicative criteria derived in
FOREST_CONNECTIVITY.md §3.2:
   u=1: (p+1)/2 has a prime factor == 3 (mod 4)
   u=2: p+2 has a prime factor == 5 or 7 (mod 8)
   u=3: (p+3)/4 has a prime factor == 2 (mod 3)
   u=4: p+4 has a prime factor == 3 (mod 4)
   u=6: p+6 has a divisor == 17 or 23 (mod 24), i.e. the subgroup of {±1}^2 generated by
        ((q/3)-sign, (2/q)) over prime factors q of p+6 contains (-1,+1)
usage: uv run python scripts/z48_forestconn_stars.py census.csv.gz
"""
import csv
import gzip
import math
import sys
from collections import Counter

from sympy import divisors, factorint, legendre_symbol

US = (1, 2, 3, 4, 6)


def star(p, u):
    cu = legendre_symbol(u, p)
    for v in divisors(p + u):
        if v > u and (v + p) % u == 0 and v <= p + 2:
            cv = legendre_symbol(v % p, p) if v % p else 0
            if cv == -cu:
                return v
    return 0


def crit(p, u):
    if u == 1:
        return any(q % 4 == 3 for q in factorint((p + 1) // 2))
    if u == 2:
        return any(q % 8 in (5, 7) for q in factorint(p + 2))
    if u == 3:
        return any(q % 3 == 2 for q in factorint((p + 3) // 4))
    if u == 4:
        return any(q % 4 == 3 for q in factorint(p + 4))
    if u == 6:
        img = {(1 if q % 3 == 1 else -1, 1 if q % 8 in (1, 7) else -1) for q in factorint(p + 6)}
        grp = {(1, 1)}
        for g in img:
            grp |= {(g[0] * h[0], g[1] * h[1]) for h in grp}
        return (-1, 1) in grp


U24 = (1, 2, 3, 4, 6, 8, 12, 24)


def main24(fn, cap_logs=(1.0, 4.0)):
    """joint failure of the stars at all u | 24 ((Z/u)^* of exponent 2): full height and height <= c·log²p."""
    rows = list(csv.DictReader(gzip.open(fn, "rt")))
    edges = [0, 10**5, 10**6, 3 * 10**6, 10**7 + 1]
    st = {}
    for r in rows:
        p = int(r["p"]); L2 = float(r["L2"])
        s = {u: star(p, u) for u in U24}
        b = next(i for i in range(4) if edges[i] < p <= edges[i + 1])
        c = st.setdefault(b, Counter())
        c["n"] += 1
        c["full"] += not any(s.values())
        for cl in cap_logs:
            c[cl] += not any(0 < v <= cl * L2 for v in s.values())
        for u in U24:
            c[f"f{u}"] += not s[u]
    print("\n| range | primes | " + " | ".join(f"star({u}) fails" for u in U24) + " | all u|24 fail (any height) | " + " | ".join(f"no u|24 star cert ≤ {cl}·log²p" for cl in cap_logs) + " |")
    print("|---|---:|" + "---:|" * (len(U24) + 1 + len(cap_logs)))
    for b in sorted(st):
        c = st[b]; n = c["n"]
        print(f"| ({edges[b]:.0e},{edges[b + 1]:.0e}] | {n} | " + " | ".join(f"{c[f'f{u}'] / n:.3f}" for u in U24)
              + f" | {c['full'] / n:.4f} ({c['full']}) | " + " | ".join(f"{c[cl] / n:.4f}" for cl in cap_logs) + " |")


def main(fn):
    rows = list(csv.DictReader(gzip.open(fn, "rt")))
    edges = [0, 10**5, 10**6, 3 * 10**6, 10**7 + 1]
    stats = {}
    mism = Counter()
    allfail = []
    for r in rows:
        p = int(r["p"])
        s = {u: star(p, u) for u in US}
        for u in US:
            if bool(s[u]) != crit(p, u):
                mism[u] += 1
        b = next(i for i in range(4) if edges[i] < p <= edges[i + 1])
        st = stats.setdefault(b, Counter())
        st["n"] += 1
        st["logp"] += math.log(p)
        for u in US:
            st[f"fail{u}"] += not s[u]
        st["fail1234_6"] += not any(s.values())
        st["fail1"] += 0
        st["H4gtL2"] += int(r["H4"]) > float(r["L2"])
        st["nomixL2"] += int(r["nmix1"]) == 0
        if not any(s.values()):
            allfail.append((p, int(r["H4"]), int(r["r"]), int(r["H4"]) / float(r["L2"]), int(r["rho"])))
    print(f"closed-form criterion mismatches per u: {dict(mism)} (0 = criterion verified on all {len(rows)} primes)")
    print("| range | primes | mean log p | star(1) fails | star(2) | star(3) | star(4) | star(6) | all five fail | (product of marginals) |")
    print("|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|")
    for b in sorted(stats):
        st = stats[b]
        n = st["n"]
        fr = [st[f"fail{u}"] / n for u in US]
        prod = math.prod(fr)
        print(f"| ({edges[b]:.0e},{edges[b + 1]:.0e}] | {n} | {st['logp'] / n:.2f} | " + " | ".join(f"{x:.4f}" for x in fr)
              + f" | {st['fail1234_6'] / n:.5f} ({st['fail1234_6']}) | {prod:.5f} |")
    print(f"\nprimes where all five stars fail: {len(allfail)}; H4/log²p among them: max {max(a[3] for a in allfail):.3f}, "
          f"mean {sum(a[3] for a in allfail) / len(allfail):.3f}; rho* values {Counter(a[4] for a in allfail).most_common(8)}")
    print(f"first 15: {[a[0] for a in allfail[:15]]}")


def adversarial(fn):
    """star failures for the list-mode primes with H4 > log^2 p (and the top-ratio family)."""
    print("\n| p | H4/log²p | failing stars among {1,2,3,4,6} |")
    print("|---:|---:|---|")
    for r in csv.DictReader(gzip.open(fn, "rt")):
        p = int(r["p"])
        if int(r["H4"]) > float(r["L2"]) or r["tag"] == "topH4ratio":
            f = [u for u in US if not crit(p, u)]
            print(f"| {p} | {int(r['H4']) / float(r['L2']):.3f} | {f} |")


if __name__ == "__main__":
    main(sys.argv[1])
    main24(sys.argv[1])
    for fn in sys.argv[2:]:
        adversarial(fn)
