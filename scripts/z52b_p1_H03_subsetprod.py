# Z1334 / Z1446: structure of S_e = {a b^{-1} mod e : ab | N} (N=(p+e)/4, Type II e-slice) inside (Z/e)^x.
# Is S_e a subgroup? Classify failures (-1 not in S_e): omega small / -1 not in H=<prime factors> / -1 in H but not in S_e.
import json
from sympy import primerange, factorint, divisors
from math import gcd
stats=dict(cases=0,subgroup=0,subgroup_nontriv=0,fail=0,fail_H=0,fail_subset=0,coset_nontriv=0)  # coset_nontriv = proper nontrivial subgroups
ex_subset=[]
for p in primerange(5,10000):
    if p%4!=1: continue
    for e in range(3,64,4):  # e ≡ -p ≡ 3 mod 4
        N=(p+e)//4
        if gcd(N,e)!=1: continue
        divs=divisors(N)
        S=set()
        for a in divs:
            for b in divs:
                if N%(a*b)==0: S.add(a*pow(b,-1,e)%e)
        # subgroup generated by prime factors
        H={1}; gens=list(factorint(N))
        frontier=[1]
        while frontier:
            x=frontier.pop(); 
            for g in gens:
                for y in (x*g%e, x*pow(g,-1,e)%e):
                    if y not in H: H.add(y); frontier.append(y)
        stats['cases']+=1
        closed=all((x*y)%e in S for x in S for y in S)
        if closed:
            stats['subgroup']+=1
            if len(S)>1: stats['subgroup_nontriv']+=1
            from sympy import totient
            if 1<len(S)<totient(e): stats['coset_nontriv']+=1; stats.setdefault('proper_examples',[]).append((p,e,len(S),int(totient(e)))) if len(stats.get('proper_examples',[]))<8 else None
        if (e-1) not in S:
            stats['fail']+=1
            if (e-1) not in H: stats['fail_H']+=1
            else:
                stats['fail_subset']+=1
                if len(ex_subset)<10: ex_subset.append([p,e,N,factorint(N),len(S),len(H)])
print(json.dumps(stats)); print(ex_subset)
json.dump(dict(stats=stats,examples=ex_subset),open('data/z52b/pass1/H03/subsetprod.json','w'),default=str)
