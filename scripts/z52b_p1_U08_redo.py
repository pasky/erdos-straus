    # Z1395: templates = (C,d): p covered iff d | 4Cp+1, d ≡ -1 (mod 4C), C <= 200.  Class r mod 840.
    def cover_class(primes, Cmax=200):
        sets = []
        for p in primes:
            s = set()
            for C in range(1, Cmax + 1):
                N = 4 * C * p + 1
                for d in good_divs(N, 4 * C):
                    s.add((C, d))
            sets.append(s)
        return sets
    def greedy(sets):
        universe = set(range(len(sets)))
        cover_by = {}
        for i, s in enumerate(sets):
            for t in s:
                cover_by.setdefault(t, set()).add(i)
        uncovered = {i for i in universe if sets[i]}
        chosen = []
        while uncovered:
            best = max(cover_by, key=lambda t: len(cover_by[t] & uncovered))
            gain = cover_by[best] & uncovered
            if not gain:
                break
            chosen.append(best)
            uncovered -= gain
        return chosen, len(uncovered)
    out = {}
    for r in [1, 121, 169, 289, 361, 529]:
        for X in [10**4, 10**5]:
            ps = [p for p in primerange(3, X + 1) if p % 840 == r]
            if len(ps) < 5:
                continue
            sets = cover_class(ps)
            ch, unc = greedy(sets)
            out[f"r{r}_X{X}"] = dict(n_primes=len(ps), templates_needed=len(ch), uncovered_C_le200=unc,
                                     first_templates=ch[:8])
    save("Z1395_dictionary_by_class", out)
