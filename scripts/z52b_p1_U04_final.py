# Z3068: shapes of certificates (complete enumeration from scriptB's U_all) for hard vs other primes, p<=1000
from math import gcd as _g
def _egypt3(num, den):
    out = []
    g = _g(num, den); a, b = num // g, den // g
    for d in divisors(factor(b * b)):
        if (d + b) % a: continue
        y = (d + b) // a; dd = b * b // d
        if (dd + b) % a: continue
        z = (dd + b) // a
        if y <= z: out.append((y, z))
    return out
def _U(n):
    res = []
    for x in range(-(-n // 4), (3 * n) // 4 + 1):
        a, b = 4 * x - n, n * x
        if a <= 0: continue
        for y, z in _egypt3(a, b):
            if x <= y: res.append((x, y, z))
    return res
