#!/usr/bin/env python3
"""z52d Pass-2 ZF1/S6 item Z1797: generate a Lean 4 proof that ES(15·2^s + 1) holds for every s with
s mod 360 ∉ {0, 240}, from the ET/divisor-class certificate produced by the repo machinery
(`scripts/z15_cert_proth_make.py 15 360 3000 OUT 999`), and state the full family statement as an open Prop
with the exact reduction to the residual classes.  Output: lean/ES/ES/Proth15.lean.
Usage: z52d_p2_ZF1_Z1797_gen_lean.py CERT.json OUT.lean
"""
import sys, json
import sympy as sp
from sympy import n_order

C = json.load(open(sys.argv[1])); OUT = sys.argv[2]
assert C['c0'] == 15 and C['b'] == 2 and C['k'] == 1
n, k = sp.symbols('n k')

def lean_poly(P):
    """integer polynomial in k with nonnegative coefficients -> Lean string"""
    P = sp.Poly(sp.expand(P), k); terms = []
    for (e,), c in sorted(P.terms()):
        assert c.is_integer and c >= 0, (P, c)
        if c == 0: continue
        t = str(c) if e == 0 else (f'{c} * k' if e == 1 else f'{c} * k ^ {e}')
        terms.append(t)
    return '(' + ' + '.join(terms) + ')' if terms else '0'

def two_split(M):
    a = 0
    while M % 2 == 0: M //= 2; a += 1
    return a, M

lemmas = []; dispatch = []; small_needed = set()
for i, cl in enumerate(C['classes']):
    M, r = cl['M'], cl['r']
    P3 = [sum(sp.Rational(c) * n ** j for j, c in enumerate(p)) for p in cl['xyz']]
    assert sp.expand(4 * P3[0] * P3[1] * P3[2] - n * (P3[0] * P3[1] + P3[1] * P3[2] + P3[0] * P3[2])) == 0
    a, w = two_split(M)
    L = n_order(2, w) if w > 1 else 1
    # residues s mod L (for s >= a) with 15*2^s+1 ≡ r (mod M)
    S = [c for c in range(L) if (15 * pow(2, c + L * 10, M) + 1) % M == r]  # c + 10L >= a
    assert S, cl
    if cl['fam'] == 'D':
        q = M
        xyz = [sp.expand(P.subs(n, q)) for P in P3]
        assert all(v.is_integer and v > 0 for v in xyz)
        lemmas.append(f"theorem ES{q} : ESProp {q} := ⟨{xyz[0]}, {xyz[1]}, {xyz[2]}, by norm_num, by norm_num, by norm_num, by norm_num⟩")
        body = f"ES_of_dvd ES{q} (by omega) (by positivity)"
        concl_n = None
    else:
        xyz = [sp.expand(P.subs(n, M * k + r)) for P in P3]
        lemmas.append(f"/-- ET class n ≡ {r} (mod {M}), family {cl['fam']} {cl['params']}. -/\n"
                      f"theorem cls_{M}_{r} (k : ℕ) : ESProp ({M} * k + {r}) := by\n"
                      f"  refine ⟨{lean_poly(xyz[0])}, {lean_poly(xyz[1])}, {lean_poly(xyz[2])}, by positivity, by positivity, by positivity, ?_⟩\n  ring")
        body = None
    # lemma in s
    cases = ' ∨ '.join(f's % {L} = {c}' for c in S)
    pre = f"theorem s_cls_{i} (s : ℕ) ({"hs" if a > 0 else "_hs"} : {max(a,1)} ≤ s) (h : {cases}) : ESProp (15 * 2 ^ s + 1) := by\n"
    pre += f"  have hp : 2 ^ s % {w} = 2 ^ (s % {L}) % {w} := pow_mod_period (by norm_num) (by norm_num) s\n" if w > 1 else ""
    pre += f"  have h2 : 2 ^ {a} ∣ 2 ^ s := pow_dvd_pow 2 (by omega)\n" if a > 0 else ""
    pre += "  norm_num at h2\n" if a > 0 else ""
    pre += "  rcases h with " + ' | '.join('h' for _ in S) + " <;> rw [h] at hp <;> norm_num at hp\n" if len(S) > 1 else "  rw [h] at hp; norm_num at hp\n"
    if body:
        pre += f"  all_goals exact {body}\n"
    else:
        pre += f"  all_goals (have e : 15 * 2 ^ s + 1 = {M} * ((15 * 2 ^ s + 1) / {M}) + {r} := by omega\n             rw [e]; exact cls_{M}_{r} _)\n"
    lemmas.append(pre)
    dispatch.append((i, L, S, max(a, 1)))

# which class covers each residue mod 360 (s >= 10)
cover = {}
for c in range(360):
    for (i, L, S, a) in dispatch:
        if c % L in S: cover[c] = i; break
resid = sorted(set(range(360)) - set(cover))
assert resid == [0, 240], resid
amax = max(a for (_, _, _, a) in dispatch)

hdr = f'''import ES.Basic
import ES.Proth3
import Mathlib

/-!
# Z1797: ES for 15·2^s + 1 — Lean statement, and everything an ET/divisor covering proves

Erdős–Straus is OPEN, and so is the thin family 15·2^s + 1 (FRONTIER §1: "Open: 15·2^s + 1, 4^s + 297"). This file
* states the family theorem `Proth15 : Prop := ∀ s, ESProp (15·2^s + 1)` (NOT proved);
* proves it for every s with s mod 360 ∉ {{0, 240}} (`proth15_offcore`), from {len(C['classes'])} Elsholtz–Tao / divisor
  classes found by `scripts/z15_cert_proth_make.py 15 360 3000` (moduli {sorted(set(c['M'] for c in C['classes']))});
* reduces `Proth15` exactly to the residual classes s ≡ 0, 240 (mod 360) (`proth15_of_core`).
The residual classes are the neighbourhood of the μ = 0 point (15·2^s + 1 → 16 at odd places), which no finite set of
ET/divisor classes covers (EXPONENT_COVERING Cor 1.5) and no constant-gap/ratio window family reaches
(DISCOVERIES (J)75 Theorem W). Generated by `scripts/z52d_p2_ZF1_Z1797_gen_lean.py`.
-/

namespace ESProth15
open ES (ESProp)
open ESProth3 (ES_of_dvd pow_mod_period)

/-- The open family statement. -/
def Proth15 : Prop := ∀ s : ℕ, ESProp (15 * 2 ^ s + 1)

theorem ES16 : ESProp 16 := ES_of_dvd ESProth3.ES4 (by norm_num) (by norm_num)
'''
small = []
for s in range(0, amax):
    if s == 0: small.append("  · exact ES16"); continue
    small.append(None)
main = f'''
/-- **ES(15·2^s + 1) off the μ = 0 core** (PROVED here, machine-checked), for s ≥ {amax}. -/
theorem proth15_offcore_large (s : ℕ) (hs : {amax} ≤ s) (h : s % 360 ≠ 0 ∧ s % 360 ≠ 240) :
    ESProp (15 * 2 ^ s + 1) := by
  have hr : s % 360 < 360 := Nat.mod_lt _ (by norm_num)
  interval_cases hc : s % 360
'''
tail_cases = []
for c in range(360):
    if c in (0, 240):
        tail_cases.append("  · exact absurd rfl h.1" if c == 0 else "  · exact absurd rfl h.2")
    else:
        i = cover[c]
        tail_cases.append(f"  · exact s_cls_{i} s (by omega) (by omega)")
main += '\n'.join(tail_cases) + '\n'
OUTS = '\n\n'.join(lemmas)
final = '''
/-- **ES(15·2^s + 1) for every s with s mod 360 ∉ {0, 240}** (PROVED here, machine-checked). -/
theorem proth15_offcore (s : ℕ) (h : s % 360 ≠ 0 ∧ s % 360 ≠ 240) : ESProp (15 * 2 ^ s + 1) := by
  rcases Nat.lt_or_ge s 4 with hs | hs
  · interval_cases s
    · simp at h
    · exact ES_of_dvd ES31 (by norm_num) (by norm_num)
    · exact ES_of_dvd ESProth3.ES61 (by norm_num) (by norm_num)
    · exact ES_of_dvd ES11 (by norm_num) (by norm_num)
  · exact proth15_offcore_large s hs h

/-- s = 0: n = 16. -/
theorem proth15_zero : ESProp (15 * 2 ^ 0 + 1) := ES16

/-- **Exact reduction**: the open family statement follows from the residual classes s ≡ 0, 240 (mod 360). -/
theorem proth15_of_core (hcore : ∀ s : ℕ, s % 360 = 0 ∨ s % 360 = 240 → ESProp (15 * 2 ^ s + 1)) :
    Proth15 := by
  intro s
  by_cases h : s % 360 ≠ 0 ∧ s % 360 ≠ 240
  · exact proth15_offcore s h
  · exact hcore s (by omega)
'''
open(OUT, 'w').write(hdr + '\n' + OUTS + '\n' + main + final + '\nend ESProth15\n')
print('classes', len(C['classes']), 'amax', amax, 'residual', resid)
