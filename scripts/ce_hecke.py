"""Kneser l-neighbour operators on the two genera G+_p, G-_p (ternary lattices of det p); compare cusp spectra.
Prediction (JL + Atkin-Lehner signs): the eigen-systems on C[G+] and C[G-] share only the Eisenstein one."""
import sys
from itertools import product
from fractions import Fraction as Fr
from ce_classes import classes, aniso_at, gram_of, canon, det3
from ce_lib import hnf
import numpy as np


def neighbours(G, l):
    out = []
    Q = lambda x: sum(G[i][j] * x[i] * x[j] for i in range(3) for j in range(3))
    B = lambda x, y: sum(G[i][j] * x[i] * y[j] for i in range(3) for j in range(3))
    lines = []
    for x in product(range(l), repeat=3):
        if not any(x):
            continue
        # normalise: first nonzero coord = 1
        f = next(c for c in x if c)
        if f != 1:
            continue
        if Q(x) % l == 0:
            lines.append(list(x))
    for x in lines:
        # lift so that Q(x) = 0 mod l^2: x -> x + l*y with 2B(x,y) = -Q(x)/l mod l
        q = Q(x) // l
        for y in product(range(l), repeat=3):
            if (2 * B(x, list(y)) + q) % l == 0:
                x2 = [x[i] + l * y[i] for i in range(3)]
                break
        assert Q(x2) % (l * l) == 0
        # L' = Z x2/l + {y in L : B(x2,y) = 0 mod l}; work in coords scaled by l
        gens = [[l * c for c in e] for e in ([1, 0, 0], [0, 1, 0], [0, 0, 1])]
        # sublattice {y: B(x2,y)=0 mod l}: generated by l*e_i and kernel vectors
        ker = [list(y) for y in product(range(l), repeat=3) if any(y) and B(x2, list(y)) % l == 0]
        rows = [[l * c for c in v] for v in ([l, 0, 0], [0, l, 0], [0, 0, l])] + [[l * c for c in v] for v in ker] + [x2]
        # rows are coordinates*l (so x2 itself represents x2/l)
        H = hnf([r[:] for r in rows])
        Bm = [[Fr(c, l) for c in r] for r in H[:3]]
        Gn = [[sum(Bm[a][i] * G[i][j] * Bm[b][j] for i in range(3) for j in range(3)) for b in range(3)] for a in range(3)]
        assert all(v.denominator == 1 for r in Gn for v in r)
        Gn = [[int(v) for v in r] for r in Gn]
        assert det3(Gn) == det3(G), (det3(Gn), det3(G))
        out.append(canon(Gn))
    return out


def hecke(cl, l):
    idx = {k: i for i, k in enumerate(cl)}
    M = np.zeros((len(cl), len(cl)))
    for k in cl:
        for k2 in neighbours(gram_of(k), l):
            M[idx[k2], idx[k]] += 1
    return M


LS = (3,)
if __name__ == "__main__":
    for p in map(int, sys.argv[1:]):
        cl = classes(p)
        mi = [k for k in cl if aniso_at(gram_of(k), p)]
        pl = [k for k in cl if not aniso_at(gram_of(k), p)]
        res = []
        for l in LS:
            em = np.sort(np.linalg.eigvals(hecke(mi, l)).real)
            ep = np.sort(np.linalg.eigvals(hecke(pl, l)).real)
            res.append((l, np.round(ep, 3), np.round(em, 3)))
        for l, ep, em in res:
            common = [x for x in ep if np.min(np.abs(em - x)) < 1e-6]
            print(p, 'T%d' % l, 'G+:', list(ep), '\n      G-:', list(em), '\n      common:', common)
