#!/usr/bin/env python3
"""Rank of the shape-cell count vectors (Theorem 2.3).

Input: output of `z49_ltfable2_scan.c N cells` — per prime p = 1 (mod 4) the ordered-word counts in the cells
(t mod 8, u mod 8, v mod 8), index 64 t + 8 u + v.  We compute (exactly, modulo a large prime, which can only
*enlarge* the null space) the space of linear relations Σ c_cell W_cell(p) = 0 valid for every listed prime, and
compare it with the relations generated by the involution u <-> v.  If the two coincide, every linear relation
among the cell counts valid for all primes is generated by the involution (PROVED by the finite computation).
We do this separately for p = 1 (8) and p = 5 (8), since the admissible cells differ, and jointly.
"""
import sys
import numpy as np

P = 2_147_483_647  # prime modulus for exact rank

def rank_mod_p(M):
    M = M.copy() % P
    rows, cols = M.shape
    r = 0
    for c in range(cols):
        piv = None
        for i in range(r, rows):
            if M[i, c] != 0: piv = i; break
        if piv is None: continue
        M[[r, piv]] = M[[piv, r]]
        inv = pow(int(M[r, c]), P - 2, P)
        M[r] = (M[r] * inv) % P
        for i in range(rows):
            if i != r and M[i, c] != 0:
                M[i] = (M[i] - M[i, c] * M[r]) % P
        r += 1
        if r == rows: break
    return r

def main(path):
    data = {}
    with open(path) as f:
        for line in f:
            parts = line.split()
            n = int(parts[0]); vec = {}
            for kv in parts[1:]:
                k, v = kv.split(':'); vec[int(k)] = int(v)
            data[n] = vec
    for label, sel in (("p=1 (8)", lambda n: n % 8 == 1), ("p=5 (8)", lambda n: n % 8 == 5), ("all p=1 (4)", lambda n: True)):
        ns = [n for n in data if sel(n)]
        occupied = sorted({c for n in ns for c in data[n]})
        idx = {c: i for i, c in enumerate(occupied)}
        M = np.zeros((len(ns), len(occupied)), dtype=np.int64)
        for i, n in enumerate(ns):
            for c, v in data[n].items(): M[i, idx[c]] = v
        rk = rank_mod_p(M)
        # involution orbits among occupied cells
        def swap(c):
            t, u, v = c >> 6, (c >> 3) & 7, c & 7
            return (t << 6) | (v << 3) | u
        orbits = set()
        for c in occupied: orbits.add(frozenset((c, swap(c))))
        n_orbits = len(orbits)
        ok = (rk == n_orbits)
        print(f"{label}: {len(ns)} primes, {len(occupied)} occupied cells, {n_orbits} involution orbits, "
              f"rank = {rk}; relation space dim = {len(occupied) - rk}; involution relations = {len(occupied) - n_orbits}"
              + ("  => relations = involution only" if ok else "  => EXTRA RELATIONS"))
        if not ok: sys.exit(1)

if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "data/z49_ltfable2/cells_3e5.txt")
