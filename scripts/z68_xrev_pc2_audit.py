"""Independent row/finite-box audit; no imports from the lane's implementation.
Run: uv run python scripts/z68_xrev_pc2_audit.py /tmp/xrev_PC2
The four replay files must first be generated by z68_pc2_events.py.
"""
from fractions import Fraction
from math import gcd, isqrt
from pathlib import Path
import sys


def records(path):
    for line in path.read_text().splitlines():
        if not line or line.startswith("#"):
            continue
        a, b, r, s, family, m, n = line.split()
        yield tuple(map(int, (a, b, r, s))) + (family, int(m), int(n))


def audit(root, p, k, q, j):
    rows = list(records(root / f"replay_{p}_{k}_{q}_{j}.txt"))
    assert p**k * q**j <= 3_000_000, "bounded finite-box audit only"
    g = [x for x in range(p**k) if pow(x % p, (p-1)//2, p) == p-1]
    h = [x for x in range(q**j) if pow(x % q, (q-1)//2, q) == q-1]
    # One bitmask per first coordinate, rather than a cylinders × box array.
    remaining = [(1 << len(h))-1 for _ in g]
    pure_g, pure_h = set(), set()
    for a, b, r, s, family, m, n in rows:
        level = p**a * q**b
        off = m // level
        assert m % level == 0 and gcd(off, p*q) == 1
        assert gcd(n, m) == 1 and n % off == 1 % off
        assert (n % p**a, n % q**b) == (r, s)
        assert a <= k and b <= j and a+b > 0
        assert (a and pow(r % p, (p-1)//2, p) == p-1) or (
            b and pow(s % q, (q-1)//2, q) == q-1), "all-residue cylinder"
        gi = [i for i, x in enumerate(g) if x % p**a == r]
        hi = [i for i, x in enumerate(h) if x % q**b == s]
        mask = sum(1 << i for i in hi)
        for i in gi:
            remaining[i] &= ~mask
        if b == 0:
            pure_g.update(gi)
        if a == 0:
            pure_h.update(hi)
    total = len(g)*len(h)
    survivors = sum(mask.bit_count() for mask in remaining)
    product = Fraction((len(g)-len(pure_g))*(len(h)-len(pure_h)), total)
    print((p, k, q, j), "rows", len(rows), "survivors", f"{survivors}/{total}",
          "pure product", product, "Gamma", product-Fraction(survivors, total))
    return rows, survivors, total


def divisors(n):
    for d in range(1, isqrt(n)+1):
        if n % d == 0:
            yield d
            if d*d != n:
                yield n//d


def named(rows, target):
    m, r = target
    assert any((row[-2], row[-1]) == target and row[4] == "II-3" for row in rows)
    witnesses = []
    for a in divisors(m//4):
        for d in divisors(m//(4*a)):
            e = m//(4*a*d)
            if gcd(4*a*d, e) == 1 and (-4*a*a*d-e) % m == r:
                witnesses.append((a, d, e))
    assert witnesses
    print("II-3", target, "independently recovered (a,d,e)", sorted(witnesses))


root = Path(sys.argv[1])
expected = {(11, 2, 13, 2): (2509, 15, 4290),
            (11, 3, 13, 2): (10188, 98, 47190),
            (11, 2, 13, 3): (9312, None, None),
            (17, 2, 19, 2): (4200, 146, 23256)}
count = 0
for spec, (nr, ns, nt) in expected.items():
    rows, survivors, total = audit(root, *spec)
    assert len(rows) == nr
    if ns is not None:
        assert (survivors, total) == (ns, nt)
    count += len(rows)
    if spec == (11, 2, 13, 2):
        named(rows, (21736, 20521))
        named(rows, (12670944, 12650497))
print("PASS:", count, "rows across four overlapping lists")
