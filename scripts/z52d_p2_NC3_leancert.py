# Z2886: certificate table for ES(n), n = 2..N, plus generator of a core-Lean (no Mathlib) checker file.
# For each n: a triple (x,y,z) with 4/n = 1/x+1/y+1/z, found by search (x<=y<=z, x <= 3n/4 etc.); written as Nat literals.
import sys
N = int(sys.argv[1]) if len(sys.argv) > 1 else 1000
def find(n):
    # 4/n = 1/x + 1/y + 1/z ; x in [ceil(n/4), floor(3n/4)]
    for x in range(-(-n // 4), (3*n)//4 + 1):
        # 4/n - 1/x = (4x - n)/(n x) = r/s reduced
        num = 4*x - n; den = n*x
        if num <= 0: continue
        # need 1/y + 1/z = num/den with y <= z, y in [ (den/num), 2*den/num ]
        ylo = -(-den // num); yhi = (2*den) // num
        for y in range(max(x, ylo), yhi + 1):
            # 1/z = num/den - 1/y = (num*y - den)/(den*y)
            a = num*y - den
            if a <= 0: continue
            b = den*y
            if b % a == 0:
                z = b // a
                if z >= y: return (x, y, z)
    return None
certs = {}
for n in range(2, N+1):
    c = find(n)
    assert c is not None, n
    x, y, z = c
    assert 4*x*y*z == n*(x*y+y*z+z*x)
    certs[n] = c
arr = ", ".join(f"({certs[n][0]}, {certs[n][1]}, {certs[n][2]})" for n in range(2, N+1))
lines = []
chunks = [certs[n] for n in range(2, N+1)]
def tup(c): return f"({c[0]}, {c[1]}, {c[2]})"
parts = []
for k in range(0, len(chunks), 100):
    seg = chunks[k:k+100]
    parts.append(f"def tab{k//100} : List (Nat × Nat × Nat) := [" + ", ".join(tup(c) for c in seg) + "]")
tabdefs = "\n\n".join(parts)
nchunks = len(parts)
appended = " ++ ".join(f"tab{i}" for i in range(nchunks))
lean = f"""/- Z2886 prototype (z52d pass 2, batch NC3): ES(n) for 2 ≤ n ≤ {N}, checked in the Lean 4 kernel with core arithmetic only
   (no Mathlib, no native_decide). Certificates generated by scripts/z52d_p2_NC3_leancert.py (search; each triple is
   re-verified by the kernel). Statement: for each n in [2,{N}] the stored triple satisfies 4xyz = n(xy+yz+zx) with x,y,z ≥ 1,
   i.e. 4/n = 1/x + 1/y + 1/z. This is a finite verified check, not a proof of ES. -/

{tabdefs}

def table : List (Nat × Nat × Nat) := {appended}

def cert (n : Nat) : Nat × Nat × Nat := (table.getD (n - 2) (0, 0, 0))

def checkAt (n : Nat) : Bool :=
  let (x, y, z) := cert n
  0 < x && 0 < y && 0 < z && 4 * (x * y * z) == n * (x * y + y * z + z * x)

set_option maxRecDepth 100000 in
theorem es_upto : ∀ n, n < {N - 1} → checkAt (n + 2) = true := by decide +kernel
"""
open('lean/ES_cert/ESCert.lean', 'w').write(lean)
print("wrote lean/ES_cert/ESCert.lean with", N-1, "certificates")
