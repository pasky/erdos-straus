"""R177 from-scratch check of bsD_frobenius_closure Thm 2.

Slice (c,d), M = 4cd.  Type II at odd n: prime factors l of N = 1 + 4c^2 d n satisfy (-dn/l) = 1; Type I: l | n^2 + 4c^2 d,
l not| n, satisfy (-d/l) = 1.  Phi = subgroup of (Z/M)^x generated by classes of primes l < B, l not| Mn, split in K.
Prediction: index [ (Z/M)^x : Phi ] = 2 if disc(K) | M (K subset Q(zeta_M)), else 1.
Also checks the necessary condition on actual prime factors of N, and the obstruction rule:
  Type II obstructed  <=> index 2 (K imaginary, so psi_K(-1) = -1);  Type I obstructed <=> (-d/n) = +1.
against actual divisor hits.
Run: PYTHONPATH=scripts uv run python scripts/review_ld_frob.py
"""
from math import gcd
from sympy import primerange, factorint, jacobi_symbol, isprime


def kron(D, l):  # Kronecker (D/l) for odd prime l
    return jacobi_symbol(D % l, l)


def sqfree(D):
    s = -1 if D < 0 else 1
    for l, v in factorint(abs(D)).items():
        if v % 2: s *= l
    return s


def disc(D):
    D0 = sqfree(D)
    return D0 if D0 % 4 == 1 else 4 * D0


def closure(M, gens):
    H = {1}
    frontier = [1]
    while frontier:
        new = []
        for h in frontier:
            for g in gens:
                y = h * g % M
                if y not in H: H.add(y); new.append(y)
        frontier = new
    return H


def phi(M):
    return sum(1 for a in range(1, M) if gcd(a, M) == 1)


def divs(n):
    ds = [1]
    for l, v in factorint(n).items():
        ds = [d * l ** k for d in ds for k in range(v + 1)]
    return ds


bad = 0; checked = 0; obst_bad = 0
ns = [p for p in primerange(5, 400)] + [m * m for m in range(3, 40, 2)]
for cd in range(1, 31):
    for c in range(1, cd + 1):
        if cd % c: continue
        d = cd // c; M = 4 * cd
        for n in ns:
            if gcd(n, M) != 1: continue
            for typ, D in (('II', -d * n), ('I', -d)):
                gens = [l % M for l in primerange(3, 3000) if (M * n) % l and kron(D, l) == 1]
                idx = phi(M) // len(closure(M, gens))
                pred = 2 if M % abs(disc(D)) == 0 else 1
                checked += 1
                if idx != pred: bad += 1; print('MISMATCH', typ, c, d, n, idx, pred)
                # necessary condition on actual prime factors, and obstruction rule vs actual hits
                if typ == 'II':
                    N = 1 + 4 * c * c * d * n
                    assert all(kron(D, l) == 1 for l in factorint(N))
                    hits = any((f + 1) % M == 0 for f in divs(N))
                    obstructed = pred == 2
                else:
                    N = n * n + 4 * c * c * d
                    assert all(kron(D, l) == 1 for l in factorint(N) if n % l)
                    hits = any((f + n) % M == 0 for f in divs(N))
                    obstructed = jacobi_symbol(-d % n, n) == 1 if isprime(n) else None
                if obstructed and hits: obst_bad += 1; print('OBSTRUCTED BUT HIT', typ, c, d, n)
print('closure tests', checked, ' index mismatches', bad, ' obstructed-but-hit', obst_bad)
