# z52b pass1 U00 fix: solver-based checks (uses scripts/z52b_p1_U00_solver.py).
import sys, json, math, random
sys.path.insert(0, 'scripts')
from z52b_p1_U00_solver import solutions
from sympy import primerange, legendre_symbol, isprime
import numpy as np
out = {}
# Z0713: k1(n), k2(n) = # solutions (unordered) with exactly one / two denominators divisible by n, n = 2..14; compare to the claimed k1, k2
k1, k2, k3 = [], [], []
for n in range(2, 15):
    s = solutions(n)
    c = [sum(1 for v in t if v % n == 0) for t in s]
    k1.append(sum(1 for x in c if x == 1)); k2.append(sum(1 for x in c if x == 2)); k3.append(sum(1 for x in c if x == 3))
out['Z0713'] = {'n_range': '2..14', 'k1': k1, 'k2': k2, 'k3': k3,
                'claimed_k1_start': [0, 2, 0, 1, 5, 5, 0, 5, 6, 6, 9], 'claimed_k2_start': [1, 1, 1, 1, 2, 2, 2, 1, 4, 3]}
# Z0095: tangent (dual-number) condition at each solution of p: the subgroup of Q generated by {1/x²,1/y²,1/z²} contains 4m/p²?
# For integer a_i, sum a_i/x_i^2 ranges over the subgroup G = gcd-group generated by 1/x_i^2.  Test: 1/p^2 ∈ G (then all 4m/p² ∈ G)
from fractions import Fraction as F
def in_group(gens, target):
    # G = Z-span of gens (rationals). Test target ∈ G via common denominator lattice: G = (1/L)·g Z, L=lcm(dens), g=gcd(nums)
    L = 1
    for x in gens: L = L * x.denominator // math.gcd(L, x.denominator)
    nums = [int(x * L) for x in gens]
    g = 0
    for v in nums: g = math.gcd(g, v)
    t = target * L
    return t.denominator == 1 and int(t) % g == 0 if g else t == 0
res = []
for p in [q for q in primerange(5, 1200) if q % 4 == 1]:
    s = solutions(p)
    ok_all = True; ok_any = False
    for t in s:
        gens = [F(1, v * v) for v in t]
        if in_group(gens, F(1, p * p)): ok_any = True
        else: ok_all = False
    res.append((p, len(s), ok_any, ok_all))
n_p = len(res)
out['Z0095'] = {'n_primes': n_p, 'primes_where_some_solution_has_1/p2_in_span': sum(1 for r in res if r[2]),
                'primes_where_all_solutions_have_1/p2_in_span': sum(1 for r in res if r[3]),
                'fail_all_first': [r[0] for r in res if not r[3]][:20]}
# Z0957: ratio buckets for primes p ≡ 1 (mod 840), p ≤ 3e4: bucket of x/p (x = smallest denominator of each solution, 8 buckets on (1/4, 3/4])
cls = [p for p in primerange(3, 30001) if p % 840 == 1]
bk = {}
for p in cls:
    s = solutions(p)
    bs = set(min(7, int((t[0] / p - 0.25) * 16)) for t in s)  # bucket of x/p in 1/16 steps
    bk[p] = bs
allb = sorted(set().union(*bk.values())) if bk else []
cov = {b: sum(1 for p in cls if b in bk[p]) / max(1, len(cls)) for b in range(8)}
out['Z0957'] = {'primes_1mod840_le_3e4': cls, 'n_solutions': {p: len(solutions(p)) for p in cls}, 'bucket_frac_present(x/p in 1/16 steps)': {b: round(cov[b], 3) for b in range(8)}}
# Z0974: near-isosceles solutions (x=y or y=z, or |x−y| ≤ 2·... ) for p ≡ 1 mod 4 up to 1200
iso = []
for p in [q for q in primerange(5, 1200) if q % 4 == 1]:
    s = solutions(p)
    near = [t for t in s if t[0] == t[1] or t[1] == t[2] or (t[2] - t[1]) <= 4]
    iso.append((p, len(near), len(s)))
out['Z0974'] = {'n_primes': len(iso), 'primes_with_isosceles_or_near': sum(1 for r in iso if r[1] > 0), 'frac': round(sum(1 for r in iso if r[1] > 0) / len(iso), 3),
                'mean_frac_near_among_all_solutions': round(float(np.mean([r[1] / r[2] for r in iso if r[2]])), 4)}
# Z0976: residues of successful first denominators mod p: fraction that are QNR mod p, for p < 500
qn = []
for p in [q for q in primerange(5, 500) if q % 4 == 1]:
    s = solutions(p)
    xs = set(t[0] % p for t in s)
    ys = set(t[1] % p for t in s)
    qn.append((p, len(xs), sum(1 for x in xs if legendre_symbol(x, p) == -1) / max(1, len(xs))))
out['Z0976'] = {'n_primes': len(qn), 'mean_frac_of_x_residues_QNR': round(float(np.mean([r[2] for r in qn])), 3),
                'example': qn[:8]}
# Z1344: KAM-type persistence, precise version: for consecutive primes p<q (≡1 mod 4, q ≤ 1000), for each solution t of q,
# is there a solution s of p with s[0] ∈ {round(t[0]·p/q) ± 1} (first denominators scale with p/q)?  Fraction of q-solutions hit.
pr = [q for q in primerange(5, 1000) if q % 4 == 1]
hits = []; tot = 0
for p, q in zip(pr, pr[1:]):
    sp = solutions(p); sq = solutions(q)
    xs_p = sorted(set(t[0] for t in sp))
    for t in sq:
        tot += 1
        target = t[0] * p / q
        hit = any(abs(x - target) <= 1 for x in xs_p)
        hits.append(hit)
rand_hit = None
out['Z1344'] = {'consecutive_pairs': len(pr) - 1, 'q_solutions_tested': tot, 'fraction_hit_within_1': round(sum(hits) / max(1, tot), 4)}
# baseline: random shift
random.seed(0); base = []
for p, q in zip(pr, pr[1:]):
    sp = solutions(p); sq = solutions(q)
    xs_p = sorted(set(t[0] for t in sp))
    for t in sq:
        target = (t[0] + random.randint(-50, 50)) * p / q
        base.append(any(abs(x - target) <= 1 for x in xs_p))
out['Z1344']['baseline_fraction_random_shift_pm50'] = round(sum(base) / max(1, len(base)), 4)
json.dump(out, open('data/z52b/pass1/U00/fix_solver.json', 'w'), indent=1, default=str)
print(json.dumps(out, indent=1, default=str)[:6000])
