# ---- Z2669 Sylver coinage (finite truncation N=24): state = semigroup generated by named numbers, truncated at N
NMAX = 24
@lru_cache(maxsize=None)
def grundy(S):
    S = set(S)
    moves = set()
    for n in range(1, NMAX+1):
        if n in S: continue
        T = set(S) | {n}
        # semigroup closure restricted to ≤ NMAX
        changed = True
        while changed:
            changed = False
            for a in list(T):
                for b in list(T):
                    s = a+b
                    if s <= NMAX and s not in T: T.add(s); changed = True
        moves.add(grundy(frozenset(T)))
    g = 0
    while g in moves: g += 1
    return g
def closure(gens):
    T = set(gens)
    changed = True
    while changed:
        changed = False
        for a in list(T):
            for b in list(T):
                s = a+b
                if s <= NMAX and s not in T: T.add(s); changed = True
    return frozenset(T)
