# z52d pass2 TO4 (Z1599): minimal index of a subgroup H ≤ (Z/m)^× with -1 ∉ H, for m = 4C ≤ 4*CMAX.
# Exact criterion (finite abelian G): min index = min{ r ≥ 2 : -1 ∉ G^r }  (cyclic quotients suffice; homs G→Z/r
# separate G/G^r). Verified against brute force over all subgroups for m ≤ 60 below.
import math, sys
CMAX=int(sys.argv[1])
def units(m): return [a for a in range(1,m) if math.gcd(a,m)==1] if m>2 else [1]
def powers(G,m,r):
    S=set()
    for g in G:
        x=pow(g,r,m); S.add(x)
    return S
def min_index(m):
    G=units(m); minus1=(m-1)%m
    if m<=2: return None
    for r in range(2, len(G)+1):
        if minus1 not in powers(G,m,r): return r
    return None
# brute-force check (all subgroups generated by subsets of size ≤ 3 — sufficient for these small groups)
def closure(gens,m):
    S={1}; fr=[1]
    while fr:
        x=fr.pop()
        for g in gens:
            y=x*g%m
            if y not in S: S.add(y); fr.append(y)
    return frozenset(S)
def brute(m):
    G=units(m); minus1=(m-1)%m
    best=None; import itertools
    subs=set()
    for k in range(1,4):
        for comb in itertools.combinations(G,k):
            subs.add(closure(comb,m))
    for H in subs:
        if minus1 in H: continue
        idx=len(G)//len(H)
        if best is None or idx<best: best=idx
    return best
ok=all(min_index(4*C)==brute(4*C) for C in range(1,16) if 4*C>2)
print("criterion agrees with brute force (m=4..60, subsets of size<=3):", ok)
hist={}; ex={}
for C in range(1,CMAX+1):
    r=min_index(4*C); hist[r]=hist.get(r,0)+1
    ex.setdefault(r,[]).append(4*C)
print("C<=%d: distribution of min index of -1-avoiding subgroup:"%CMAX, dict(sorted(hist.items(),key=lambda t: (t[0] is None, t[0]))))
for r in sorted(k for k in ex if k is not None and k>2): print(" index",r,"for m=4C in",ex[r][:12],"..." if len(ex[r])>12 else "")
