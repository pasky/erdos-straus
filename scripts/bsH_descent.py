"""O181 DRINFELD_ES §4 / memos bsH_odd_descent, bsH_carlitz_real: cheap checks.
(1) For ES moduli M = 4m (8 <= M <= 400): for every subgroup H of (Z/M)^* that is the Galois group of ℚ(ζ_M)/F' with
    F' of ODD degree (index of H odd) and every index-2 H' < H: |H \\ H'| and whether H \\ H' = {-1}.
(2) Prop 4.2 identity N(β)N(β') = (1+x)^r = 1 + x R_r and R_r ≡ r (mod x) on random integers.
(3) Carlitz: parity of [K_M^+ : F] = Phi(M)/(q-1) for M irreducible of degree d (= (q^d-1)/(q-1)) and M = T^e."""
import math, random
from itertools import product


def units(M):
    return [a for a in range(1, M) if math.gcd(a, M) == 1]


def subgroups_cyclic_gen(M, G):
    # all subgroups generated by <= 2 elements (enough to enumerate all subgroups for these M)
    subs = set()
    for a in G:
        for b in G:
            S = {1}
            frontier = [1]
            while frontier:
                x = frontier.pop()
                for g in (a, b):
                    y = x * g % M
                    if y not in S:
                        S.add(y); frontier.append(y)
            subs.add(frozenset(S))
    return subs


bad = 0; checked = 0
for M in range(8, 401, 4):
    G = units(M)
    phi = len(G)
    subs = subgroups_cyclic_gen(M, G) if M <= 120 else set()
    for H in subs:
        if (phi // len(H)) % 2 == 0:
            continue  # F' of even degree
        for Hp in subs:
            if len(Hp) * 2 == len(H) and Hp <= H:
                checked += 1
                diff = H - Hp
                if diff == {M - 1}:
                    bad += 1
print(f"(1) M <= 120: {checked} (odd-degree F', quadratic K') pairs; pairs with H minus H' = {{-1}}: {bad}")

ok = True
for _ in range(1000):
    x = random.randrange(2, 10**6); r = random.choice([1, 3, 5, 7])
    R = ((1 + x) ** r - 1) // x
    ok &= ((1 + x) ** r == 1 + x * R) and (R - r) % x == 0
print("(2) (1+x)^r = 1 + x R_r and R_r ≡ r mod x on 1000 samples:", ok)

for q in (3, 5, 7, 9, 11, 13):
    row = [((q ** d - 1) // (q - 1)) % 2 for d in range(1, 9)]
    rowT = [((q ** e - q ** (e - 1)) // (q - 1)) % 2 for e in range(1, 9)]
    print(f"(3) q={q}: parity of [K_M^+:F], M irreducible deg d=1..8: {row}; M = T^e, e=1..8: {rowT}")
