"""Z1343/Z1444/Z1394 check: for primes p = 1 (mod 4), p <= PMAX, and C <= CMAX, N = 4Cp+1 (≡1 mod 4C).
B(p,C) := some divisor d | N has d ≡ -1 (mod 4C)  (exact Type-II witness, equivalent to ES via C).
A(p,C) := -1 lies in the SUBGROUP of (Z/4C)^* generated by the prime factors of N (mod 4C).
Note B ⇒ A (a divisor ≡ -1 is a product of prime factors). Gap = A and not B (the 'G4' gap).
Also: longest run of consecutive primes ≡1 mod 24 with no C<=2 witness. Memory: O(number of divisors of N). """
import json, sys
from math import gcd
PMAX = int(sys.argv[1]) if len(sys.argv) > 1 else 20000
CMAX = int(sys.argv[2]) if len(sys.argv) > 2 else 30
def primes_upto(n):
    s = bytearray([1]) * (n + 1); s[0] = s[1] = 0
    for i in range(2, int(n ** 0.5) + 1):
        if s[i]: s[i*i::i] = bytearray(len(s[i*i::i]))
    return [i for i in range(n + 1) if s[i]]
def factor(n):
    f = {}; d = 2
    while d * d <= n:
        while n % d == 0: f[d] = f.get(d, 0) + 1; n //= d
        d += 1
    if n > 1: f[n] = f.get(n, 0) + 1
    return f
def subgroup_contains(gens, m, target):
    H = {1 % m}; frontier = [1 % m]
    gens = [g % m for g in gens if gcd(g, m) == 1]
    while frontier:
        new = []
        for h in frontier:
            for g in gens:
                k = h * g % m
                if k not in H: H.add(k); new.append(k)
        frontier = new
    return (target % m) in H
def divisor_residues(fac, m):
    res = {1 % m}
    for q, e in fac.items():
        res = {r * pow(q, k, m) % m for r in res for k in range(e + 1)}
    return res
ps = [p for p in primes_upto(PMAX) if p % 4 == 1 and p > 5]
cnt = {"AB": 0, "A_notB": 0, "notA": 0}; gaps = []; minC = {}; nowitness_C = []
for p in ps:
    best = None
    for C in range(1, CMAX + 1):
        m = 4 * C; N = m * p + 1
        fac = factor(N)
        A = subgroup_contains([q for q in fac if N % q == 0 and q != 1 and gcd(q, m) == 1], m, m - 1)
        Bres = (m - 1) in divisor_residues(fac, m) if m > 1 else True
        # note: d ≡ -1 mod m and d | N; -1 ≡ m-1
        if Bres:
            cnt["AB"] += 1
            if best is None: best = C
        elif A:
            cnt["A_notB"] += 1; gaps.append((p, C))
        else:
            cnt["notA"] += 1
    minC[p] = best
hard = [p for p in ps if minC[p] is None]
# runs of consecutive primes ≡1 mod 24 with minC > 2 (no C<=2 witness)
p24 = [p for p in ps if p % 24 == 1]
best_run = cur = 0; best_span = None; start = None
for i, p in enumerate(p24):
    if minC[p] is None or minC[p] > 2:
        cur += 1
        if cur == 1: start = p
        if cur > best_run: best_run = cur; best_span = (start, p)
    else:
        cur = 0
res = {"PMAX": PMAX, "CMAX": CMAX, "n_primes_1mod4": len(ps), "counts_over_(p,C)": cnt,
       "n_gap_pairs(A,notB)": len(gaps), "gap_head": gaps[:20],
       "primes_with_no_witness_C<=CMAX": hard,
       "minC_distribution": {str(c): sum(1 for p in ps if minC[p] == c) for c in range(1, CMAX + 1)},
       "longest_run_1mod24_without_C<=2_witness": {"length": best_run, "span": best_span,
                                                  "n_primes_1mod24": len(p24)}}
print(json.dumps(res, indent=1, default=str))
json.dump(res, open(f"data/z52b/pass1/U04/gate_check_{PMAX}_{CMAX}.json", "w"), indent=1, default=str)
