# z70 CLASS item 1, residual hunt: the FIBRE-PRINCIPAL null PSF and the decomposition of the L1 overlaps.
# Lemma FIB (Z70_CLASS.md §1.4): (2ad + sqrt(-dn)) = D_d * B_a with N(B_a) = N_a = n + 4a^2 d, and every e-ideal of a
#   fibre-a solution divides B_a.  Hence [B_a] = T_d (principal relation) and for e-ideals E, E' of fibre a with coprime norms
#   [E] + [E'] = T_d - [W],  W = B_a/(E E'),  N(W) = N_a/(e e')   (CS = the case W = 1; Lemma DL = ideal identities).
# NULL PSF = PSC + principality of B_a imposed for EVERY active fibre a (a = first letter of some solution):
#   prime classes: q <= QFIX and translation primes fixed; other primes up to QPOOL swapped (genus-preserving injection, as PSC);
#   primes > QPOOL (only in cofactors A) get a uniform random class of their genus coset;  then one PIVOT prime per active
#   fibre (exponent 1 in N_a, dividing N_a for no other active fibre, not fixed) gets the class that makes [B_a] = T_d.
#   Preserves: every ideal identity, every fibre-principal relation (DL, CS, and the general Lemma FIB), inversion closure.
#   Randomises: class coincidences not generated by these (principal ideals other than the active beta_a).
# Diagnostics (observed only): every L1 overlap pair (x, x+t0) realised by good ideals I, J ([I] = x, [J] = x + t0) is
#   classified  ID  (J = I * L0^{+-1}, an ideal identity),  FIB (I and J, or I and conj J, divide a common active B_a),  OTHER.
# Usage: python scripts/z70_class_psf.py d R seed range P0 P1 [mod res] | list n1 ...
import sys, math, random, os
MATCH2 = os.environ.get('Z70_MATCH2') == '1'
sys.path.insert(0, 'scripts')
from collections import Counter
from sympy import factorint, primerange
from z69_twist_i17 import reduce
from z70_class_core import Fact, ClassData, solutions, good_ideals
from z70_class_null import stats, translations, SplitPrimes, QFIX, SS

def analyse(n, d, R, rng, F):
    sols = solutions(n, d, F)
    gi = good_ideals(n, d, F, sols)
    if not gi: return dict(n=n, d=d, k=0)
    C = ClassData(n, d); G = C.G
    vk = {}
    for (e, rho) in gi:
        v = tuple(C.ideal_vector(e, rho, F)); vk[v] = 1; vk[tuple((q, -k) for q, k in v)] = 1
    vecs = list(vk)
    Xobs = [C.vec_class(v) for v in vecs]
    if len(set(Xobs)) < 2: return dict(n=n, d=d, k=len(set(Xobs)))
    tl, tlp = translations(C)
    obs = stats(G, Xobs, tl)
    # active fibres and the prime-ideal vectors of B_a
    fib = {}
    for (a, b, c, e) in sols:
        if a in fib: continue
        Na = n + 4*a*a*d; A = 4*a*c*d - 1; assert A*e == Na
        fac = dict(F.factor(e))
        for q, k in factorint(A).items(): fac[q] = fac.get(q, 0) + k
        vec = []
        for q, k in sorted(fac.items()):
            r, _ = C.prime_class(q); rr = (2*a*d) % q
            vec.append((q, k if rr == r else -k)); assert rr in (r, q - r)
        fib[a] = vec
        # sanity: principal relation [B_a] = T_d in the real class group
        assert C.vec_class(vec) == C.Td, (n, d, a)
    goodprimes = sorted(set(q for v in vecs for q, _ in v))
    fixed = set(q for q in goodprimes if q <= QFIX) | set(tlp)
    for v in fib.values():
        for q, _ in v:
            if q <= QFIX: fixed.add(q)
    QPOOL = max(goodprimes)
    # --- integer elimination of the principal relations  sum_q k_q [Q_q] = T_d  (one per active fibre)
    # fixed primes are moved to the right-hand side; pivots must have coefficient +-1; prefer primes outside good norms, then large.
    gp = set(goodprimes)
    cons = []
    for a, v in fib.items():
        rhs = C.Td; co = {}
        for q, k in v:
            if q in fixed:
                c = C.prime_class(q)[1] if k < 0 else G.negd[C.prime_class(q)[1]]
                for _ in range(abs(k)): rhs = G.add(rhs, c)
            else: co[q] = co.get(q, 0) + k
        cons.append([co, rhs])
    def gmul(x, m):
        y = G.one; c = x if m > 0 else G.negd[x]
        for _ in range(abs(m)): y = G.add(y, c)
        return y
    piv = []           # list of (pivot prime, coef, constraint index)
    unpinned = 0
    for i in range(len(cons)):
        co, rhs = cons[i]
        cands = [q for q, k in co.items() if abs(k) == 1 and k != 0]
        if not cands:
            if any(co.values()): unpinned += 1
            continue
        q = max(cands, key=lambda q: (q not in gp, q))
        kq = co[q]
        for j in range(len(cons)):
            if j == i: continue
            cj, rj = cons[j]
            m = cj.get(q, 0)
            if m == 0: continue
            f = -m * kq                     # cj += f * co   (kq = +-1, so f*kq = -m and q cancels)
            for qq, kk in co.items():
                cj[qq] = cj.get(qq, 0) + f * kk
                if cj[qq] == 0: del cj[qq]
            cons[j][1] = G.add(rj, gmul(rhs, f))
        piv.append((q, kq, i))
    pivots = set(q for q, _, _ in piv)
    allprimes = sorted(set(q for v in fib.values() for q, _ in v) | gp)
    swap = [q for q in allprimes if q not in fixed and q not in pivots and q <= QPOOL]
    big = [q for q in allprimes if q not in fixed and q not in pivots and q > QPOOL]
    SP = SplitPrimes(n, d, int(QPOOL * 1.6) + 100)
    pools = {q: SP.pool(q) for q in swap}
    if MATCH2:      # variant (post hoc diagnostic): swap only to primes whose class has the same 2-Sylow projection m*[Q]
        m = G.h
        while m % 2 == 0: m //= 2
        def proj(q):
            x = C.prime_class(q)[1]; y = G.one
            for _ in range(m): y = G.add(y, x)
            return y
        for q in swap:
            pq = proj(q); dl = 0.1; P = []
            while len(P) < 8:
                P = [x for x in SP.pool(q, delta=dl, kmin=8) if proj(x) == pq]; dl *= 1.5
                if dl > 3: break
            pools[q] = P if P else [q]
    # sanity: the real classes satisfy the eliminated system
    realc = {q: C.prime_class(q)[1] for q in allprimes}
    for q, kq, i in piv:
        co, rhs = cons[i]; tot_ = G.one
        for qq, kk in co.items(): tot_ = G.add(tot_, gmul(realc[qq], kk))
        assert tot_ == rhs, (n, d, 'elimination inconsistent')
    H = set(G.add(u, u) for u in G.coords.values()); Hl = list(H)
    # --- diagnostics on the L1 pairs
    diag = Counter()
    if tl:
        l0 = tlp[0]; byc = {}
        for v, x in zip(vecs, Xobs): byc.setdefault(x, []).append(dict(v))
        fibsets = [dict(v) for v in fib.values()]
        def divides(I, B):   # ideal I (dict q -> signed exp) divides B (dict)
            return all((q in B) and (B[q] * k > 0) and abs(B[q]) >= abs(k) for q, k in I.items())
        for x in set(Xobs):
            y = G.add(x, tl[0])
            if y not in byc: continue
            kind = 'OTHER'
            for I in byc[x]:
                for J in byc[y]:
                    diff = dict(J)
                    for q, k in I.items(): diff[q] = diff.get(q, 0) - k
                    diff = {q: k for q, k in diff.items() if k}
                    if len(diff) == 1 and l0 in diff and abs(diff[l0]) == 1: kind = 'ID'; break
                if kind == 'ID': break
            if kind == 'OTHER':
                for I in byc[x]:
                    for J in byc[y]:
                        Jc = {q: -k for q, k in J.items()}
                        if any(divides(I, B) and (divides(J, B) or divides(Jc, B)) for B in fibsets): kind = 'FIB'; break
                    if kind == 'FIB': break
            diag[kind] += 1
    acc = {s: [] for s in SS}
    first = None; varied = [False]*len(vecs)
    for _ in range(R):
        cls = {q: C.prime_class(q)[1] for q in fixed}
        used = set(fixed)
        for q in rng.sample(swap, len(swap)):
            cand = [x for x in pools[q] if x not in used]
            if not cand and MATCH2: cand = [q] if q not in used else []
            if not cand: cand = [x for x in SP.pool(q, delta=1.0, kmin=len(used) + 8) if x not in used]
            x = rng.choice(cand); used.add(x); cls[q] = C.prime_class(x)[1]
        for q in big:
            # uniform class in the genus coset of Q_q
            cls[q] = G.add(C.prime_class(q)[1], rng.choice(Hl))
        for q, kq, i in piv:                       # pivots are eliminated from every other constraint: solve directly
            co, rhs = cons[i]; rest = G.one
            for qq, kk in co.items():
                if qq != q: rest = G.add(rest, gmul(cls[qq], kk))
            val = G.add(rhs, G.negd[rest]); cls[q] = val if kq > 0 else G.negd[val]
        def vc(v):
            x = G.one
            for q, k in v:
                c = cls[q] if k > 0 else G.negd[cls[q]]
                for _ in range(abs(k)): x = G.add(x, c)
            return x
        Y = [vc(v) for v in vecs]
        if first is None: first = Y
        else: varied = [vv or (y != f) for vv, y, f in zip(varied, Y, first)]
        st = stats(G, Y, tl)
        for k_ in SS: acc[k_].append(st[k_])
    nullst = {k_: (sum(v)/R, (sum(x*x for x in v)/R - (sum(v)/R)**2) ** 0.5) for k_, v in acc.items()}
    return dict(n=n, d=d, h=G.h, k=obs['K'], nsol=len(sols), NI=len(vecs), obs=obs, null=nullst, diag=diag,
                nfib=len(fib), unpinned=unpinned, l0=tlp[0] if tlp else None, nvar=sum(varied))

def run(d, R, nlist, F, seed, out=sys.stdout, tag=''):
    rng = random.Random(seed)
    agg = {s: [0.0, 0.0] for s in SS}; npr = 0; tot = Counter()
    for n in nlist:
        o = analyse(n, d, R, rng, F)
        if 'obs' not in o:
            print(f"n={n} d={d} k={o['k']} (skipped)", file=out, flush=True); continue
        npr += 1; ob = o['obs']
        line = (f"n={n} d={d} h={o['h']} nsol={o['nsol']} NI={o['NI']} k={o['k']} fibres={o['nfib']} unpinned={o['unpinned']} varied={o['nvar']}/{o['NI']} "
                f"l0={o['l0']} L1:ID/FIB/OTHER={o['diag']['ID']}/{o['diag']['FIB']}/{o['diag']['OTHER']} |")
        for s in SS:
            mu, sd = o['null'][s]; line += f" {s} {ob[s]} ({mu:.1f}±{sd:.1f})"
            agg[s][0] += ob[s] - mu; agg[s][1] += sd*sd; tot['obs_'+s] += ob[s]; tot['null_'+s] += mu
        for k in ('ID', 'FIB', 'OTHER'): tot[k] += o['diag'][k]
        tot['fib'] += o['nfib']; tot['unp'] += o['unpinned']; tot['var'] += o['nvar']; tot['NI'] += o['NI']
        print(line, file=out, flush=True)
    Z = lambda a: a[0]/math.sqrt(a[1]) if a[1] > 0 else float('nan')
    print(f"# {tag} null=PSF{'(MATCH2)' if MATCH2 else ''} d={d} n analysed {npr}; R={R}; seed={seed}; active fibres {tot['fib']} (unpinned {tot['unp']}); good ideals with a non-degenerate null class {tot['var']}/{tot['NI']}; "
          f"L1 overlaps ID/FIB/OTHER = {tot['ID']}/{tot['FIB']}/{tot['OTHER']}", file=out)
    print(f"# {tag} null=PSF d={d}: " + "; ".join(f"Z_{s} = {Z(agg[s]):+.2f} (obs {tot['obs_'+s]:.0f}, null {tot['null_'+s]:.1f})" for s in SS), file=out, flush=True)

if __name__ == "__main__":
    d = int(sys.argv[1]); R = int(sys.argv[2]); seed = int(sys.argv[3]); spec = sys.argv[4:]
    if spec[0] == 'range':
        P0, P1 = int(spec[1]), int(spec[2])
        mod, res = (int(spec[3]), int(spec[4])) if len(spec) > 4 else (8, 1)
        nl = [p for p in primerange(P0, P1) if p % mod == res]
    else:
        nl = sorted(set(int(x) for x in spec[1:]))
    F = Fact(max(nl)//3 + 10)
    run(d, R, nl, F, seed=seed, tag=' '.join(spec[:3]))
