"""Independent, bounded audit of z49 ltfable2. Run with uv and an OS memory limit.
No imports from the reviewed implementation. Source cell data only select a small
rank witness; every selected row is independently regenerated by a t,u loop.
"""
from collections import Counter
from fractions import Fraction
from itertools import product
from math import gcd, isqrt, lcm, prod
from pathlib import Path
import sys
from sympy import divisors, factorint, isprime, jacobi_symbol, primerange
from sympy.ntheory.modular import crt

SOURCE = Path(sys.argv[1] if len(sys.argv)>1 else '/home/pasky/projects/math/erdos-straus-claude-agent-worktree-0041')
MOD = 1000003


def words(n):
    # u <= v implies t*u*u <= n+2u; t*u-1 divides n+u.
    out = set()
    for u in range(1, isqrt(n+1)+2):
        for t in range(1, (n+2*u)//(u*u)+1):
            a = t*u-1
            if a > 0 and (n+u) % a == 0:
                v = (n+u)//a
                if v >= u:
                    out.update(((t,u,v), (t,v,u)))
    return out


def cert(w):
    t,u,v = w
    return any(x % 4 == 0 for x in (t,u,v,t*u-1,t*v-1))


def in_c(x,n):
    return x % 4 == 0 or (x+n) % 8 == 0


def free_formula(n):
    out = set()
    for u in (1,2):
        for v in divisors(n+u):
            if ((n+u)//v+1) % u == 0:
                t = ((n+u)//v+1)//u
                if in_c(v,n) or in_c(t,n):
                    out.update(((t,u,int(v)),(t,int(v),u)))
    for t in (1,2):
        for d in divisors(t*n+1):
            if (d+1) % t == 0 and ((t*n+1)//d+1) % t == 0:
                u,v = (d+1)//t, ((t*n+1)//d+1)//t
                if min(u,v)>=3 and (in_c(u,n) or in_c(v,n)):
                    out.add((t,int(u),int(v)))
    return out


def small_checks():
    cells=0
    for t,u,v in product(range(8),repeat=3):
        n=(t*u*v-u-v)%8
        if n%4==1:
            cells+=1
            assert cert((t,u,v)) == any(in_c(x,n) for x in (t,u,v))
    nw=nn=0
    for n in range(1,2001,4):
        ws=words(n)
        for w in ws:
            t,u,v=w
            nw+=1
            assert t*u*v-u-v==n
            assert cert(w)==any(in_c(x,n) for x in w)
            if gcd(u*v,n)==1:
                assert cert(w)==(jacobi_symbol(u*v,n)==-1)
            assert cert(w)==(jacobi_symbol(t*u-1,n)==-1)
        assert free_formula(n)=={w for w in ws if min(w)<=2 and cert(w)}
        if isqrt(n)**2==n:
            assert not any(map(cert,ws))
        if isprime(n) and n%8==1:
            hc=min(x for w in ws for x in w if in_c(x,n))
            pred=any(q%4==3 for m in (n+4,4*n+1) for q in factorint(m))
            assert (hc==4)==pred
        for r in range(1,isqrt(n)+1):
            for s in range(r,(n-r)//(r+1)+1):
                if (n-r-s)%(r*s): continue
                t=(n-r-s)//(r*s)
                if t<1: continue
                d=t*r+1
                if d%2==0: continue
                nn+=1
                actual=jacobi_symbol(d,n)
                if t%4==1: predicted=jacobi_symbol(-1,d)
                elif t%4 in (0,3): predicted=1
                elif (t//2)%4==1: predicted=jacobi_symbol(-2,d)
                else: predicted=jacobi_symbol(2,d)
                assert actual==predicted
    print('Small audit:',cells,'cells;',nw,'positive words;',nn,'odd-numerator negative words; PASS')
    for n in (17,241,193,409,577,2521,3361,5569,9601,66529,8813281):
        ws=words(n)
        hc=min(x for w in ws for x in w if in_c(x,n))
        print('control',n,'W',len(ws),'N-',sum(map(cert,ws)),'HC',hc)
        if n in (17,241):
            assert all(all(x%8 for x in (t,u,v,t*u-1,t*v-1)) for t,u,v in ws)
    assert len(words(105))==11 and all(min(w)<=2 and not cert(w) for w in words(105))
    assert 11*3*3+3+3==105 and jacobi_symbol(34,105)==-1
    assert 56%7==0 and (7+49)%7==0 and (49+7+7)%(7*7)!=0
    print('Counterexample to unqualified square divisor wording: n=49, u=v=7, v|n+u and v=-n (mod u), but no word.')


def add_row(row,basis):
    row=[int(x)%MOD for x in row]
    for c in range(len(row)):
        if row[c]==0: continue
        if c in basis:
            a=row[c]; b=basis[c]
            row=[(x-a*y)%MOD for x,y in zip(row,b)]
        else:
            a=pow(row[c],-1,MOD)
            basis[c]=[(a*x)%MOD for x in row]
            return True
    return False


def rank_check():
    assert isprime(MOD)
    candidates={}
    with (SOURCE/'data/z49_ltfable2/cells_3e5.txt').open() as f:
        for line in f:
            p,*items=line.split()
            candidates[int(p)]={int(k):int(v) for k,v in (s.split(':') for s in items)}
    for r in (1,5):
        # One column per endpoint-swap orbit. These are W_c, not orbit sums.
        cols=[(t<<6)|(u<<3)|v for t,u,v in product(range(8),repeat=3)
              if u<=v and (t*u*v-u-v)%8==r]
        assert len(cols)==42
        selection={}; selected=[]
        for p,counts in candidates.items():
            if p%8!=r: continue
            if add_row([counts.get(c,0) for c in cols],selection): selected.append(p)
            if len(selection)==42: break
        independent={}
        for p in selected:
            assert isprime(p)
            counts=Counter(((t%8)<<6)|((u%8)<<3)|(v%8) for t,u,v in words(p))
            assert dict(counts)==candidates[p],p
            add_row([counts.get(c,0) for c in cols],independent)
        assert len(independent)==42
        print('Independent rank',r,'mod 8:',len(independent),'mod',MOD,'; pivot primes:',selected)
    print('Combined rank 84 by the two disjoint 42-column blocks; PASS')


def dickson_checks():
    for X,K in ((4,1),(5,3),(8,8),(12,16)):
        k=max(1,(K-1).bit_length())
        primes=[]
        for q in primerange(2*X+3,10000):
            if q%4==1: primes.append(q)
            if len(primes)==k: break
        L=prod(primes)
        Q0=lcm(24,*(u*(u+1) for u in range(2,X+1)),*list(primerange(1,2*X+3)))
        Q1=Q0*prod(factorint(Q0)); M=Q1*L*L
        p0=int(crt([Q1,L*L],[1,L-1])[0])
        nums=[(p0,M),(p0+1,M)]+[(p0+u,M) for u in range(2,X+1)]+[(t*p0+1,t*M) for t in range(3,X+1)]+[(2*p0+1,2*M)]
        den=[1,2*L]+[u+1 for u in range(2,X+1)]+[t+1 for t in range(3,X+1)]+[3]
        assert all(a%d==b%d==0 for (a,b),d in zip(nums,den))
        forms=[(a//d,b//d) for (a,b),d in zip(nums,den)]
        assert len(forms)==2*X and len({b for a,b in forms})==2*X
        assert all(gcd(a,b)==1 for a,b in forms)
        for ell in primerange(2,1000):
            forbidden=set()
            for a,b in forms:
                if b%ell==0: assert a%ell!=0
                else: forbidden.add((-a*pow(b,-1,ell))%ell)
            assert len(forbidden)<ell
        print('CRT admissibility checks: X',X,'K',K,'forms',len(forms),'PASS')
        if X==4:
            assert (Q0,Q1,M,p0)==(840,176400,29811600,28929601)
            for s in (1230505,6081703,11577829):
                assert all(isprime(a+b*s) for a,b in forms)
                p=p0+M*s; ws=set()
                for u in range(1,X+1):
                    for a in divisors(p+u):
                        if (a+1)%u==0:
                            t=(a+1)//u; v=(p+u)//a
                            ws.update(((t,u,v),(t,v,u)))
                for t in range(1,X+1):
                    for a in divisors(t*p+1):
                        if (a+1)%t==0 and ((t*p+1)//a+1)%t==0:
                            ws.add((t,(a+1)//t,((t*p+1)//a+1)//t))
                assert len(ws)==27 and all(min(w)<=2 and not cert(w) for w in ws)
                print('CRT instance',p,': 27 free monochromatic window words; PASS')


def genus_checks():
    for p in (17,193,409,577):
        total=Fraction(0); hits=ng=0
        for u in range(1,(p+1)//3+1):
            for b in range(1,(p+u)//(4*u-1)+1):
                if gcd(u,b)>1 or (u+b)%2==0: continue
                q=4*u*b; a=-(u+b)
                units=[j for j in range(q) if gcd(j,q)==1]
                roots=sum((a*j*j-p)%q==0 for j in units)
                ng+=bool(roots); total+=Fraction(roots,len(units))
                hits+=(p-a)%q==0
        assert hits==sum(t%4==0 for t,u,v in words(p))
        print('Direct square-twist enumeration',p,'R',hits,'genus pairs',ng,'Mgen',float(total),'exact',total)
        if p==409: assert abs(float(total)-4)<0.005 and ng==34 and hits==0
        if p==577: assert ng==40 and hits==0


if __name__=='__main__':
    small_checks()
    rank_check()
    dickson_checks()
    genus_checks()
    print('ALL INDEPENDENT CHECKS PASSED')
