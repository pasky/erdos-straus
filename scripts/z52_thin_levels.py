"""z52 deep thin-pointwise §2.2: layers of the level-t (★) event at a prime p.
For t = 4C, N = tp+1, prime factors l_i (with exponents), G = (Z/t)^*:
  SUB : -1 in <l_i>                (subgroup / cap-relaxation layer)
  GEN : image of -1 in G/G^2 lies in the F_2-span of the images of the l_i   (genus layer)
  HIT : some divisor d | N has d ≡ -1 (mod t)  ((★) at level t)
Also: levels with exponent(G) = 2 (t | 24) where GEN = HIT is forced (DETERMINISTIC_EXISTENCE Prop 3.3(b)).
Usage: uv run --with sympy python scripts/z52_thin_levels.py P0 P1 CMAX"""
import sys
from sympy import factorint, primerange, totient
from math import gcd
from itertools import product

def units(t): return [a for a in range(1, t) if gcd(a, t) == 1]

def analyse(p, C):
    t = 4 * C; N = t * p + 1
    f = factorint(N)
    U = units(t)
    sq = {(a * a) % t for a in U}
    # subgroup generated by prime factors
    gens = [l % t for l in f]
    H = {1}; frontier = [1]
    while frontier:
        x = frontier.pop()
        for g in gens:
            y = (x * g) % t
            if y not in H: H.add(y); frontier.append(y)
    SUB = (t - 1) in H
    # genus: span mod squares; build coset reps of G/G^2 as frozensets
    def cls(a): return frozenset((a * s) % t for s in sq)
    span = {cls(1)}
    for g in gens:
        span |= {cls((min(c) * g) % t) for c in span}
    GEN = cls(t - 1) in span
    # divisor residues
    res = {1}
    for l, e in f.items():
        new = set()
        for r in res:
            x = r
            for _ in range(e + 1):
                new.add(x); x = (x * l) % t
        res = new
    HIT = (t - 1) in res
    return SUB, GEN, HIT

if __name__ == "__main__":
    P0, P1, CMAX = map(int, sys.argv[1:4])
    stats = {}
    for p in primerange(P0, P1):
        if p % 4 != 1: continue
        for C in range(1, CMAX + 1):
            key = 'exp2' if 24 % (4 * C) == 0 else 'other'
            s = stats.setdefault(key, [0, 0, 0, 0, 0])
            SUB, GEN, HIT = analyse(p, C)
            s[0] += 1; s[1] += SUB; s[2] += GEN; s[3] += HIT; s[4] += (GEN and not HIT)
            assert (not HIT) or (GEN and SUB)
            if key == 'exp2': assert GEN == HIT
    for k, s in stats.items():
        print(f"{k:6s} pairs={s[0]}  SUB={s[1]/s[0]:.3f}  GEN={s[2]/s[0]:.3f}  HIT={s[3]/s[0]:.3f}  GEN&!HIT={s[4]/s[0]:.3f}")
