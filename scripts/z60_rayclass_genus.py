"""z60 RAYCLASS: the class-visible (genus) layer of the level-C event at the falsifier sets.
For n and level C:  hit_C(n)  := some divisor d of 4Cn+1 has d ≡ -1 (mod 4C)                     [the (★) event]
                    GV_C(n)   := some divisor d of 4Cn+1 has chi(d) = chi(-1) for every real character chi mod 4C
                                 (d ≡ -1 modulo squares of (Z/4C)^*: the most that ring class groups of ANY order of
                                 Q(sqrt(-Cn)) can see, §3 Prop 3.1).
GV_C = hit_C exactly when (Z/4C)^* has exponent 2, i.e. C in {1,2,3,6}.
usage: python z60_rayclass_genus.py FILE CMAX [even]   -> per n: #C<=CMAX with GV, #C with hit, least C with GV & no hit
"""
import sys
import cypari2
pari = cypari2.Pari()
def real_char_basis(M):
    # quadratic characters mod M as functions; generated by (./l) for odd l | M and chi_-4, chi_8 when 4|M, 8|M
    fac = pari.factor(M); ps = [int(x) for x in fac[0]]; es = [int(x) for x in fac[1]]
    chars = []
    for l, e in zip(ps, es):
        if l == 2:
            if e >= 2: chars.append(lambda d: 1 if d % 4 == 1 else -1)
            if e >= 3: chars.append(lambda d: 1 if d % 8 in (1, 7) else -1)
        else:
            chars.append(lambda d, l=l: int(pari.kronecker(d, l)))
    return chars
def level(n, C):
    M = 4 * C; N = 4 * C * n + 1
    chars = real_char_basis(M)
    target = [ch(M - 1) for ch in chars]
    gv = hit = False
    for d in pari.divisors(N):
        d = int(d)
        if d % M == M - 1: hit = True; gv = True; break
        if not gv and [ch(d) for ch in chars] == target: gv = True
    return gv, hit
if __name__ == "__main__":
    fn, CMAX = sys.argv[1], int(sys.argv[2]); even = len(sys.argv) > 3
    for line in open(fn):
        if not line.strip() or line.startswith('#'): continue
        n = int(line.split()[0])
        ngv = nhit = 0; least = None
        for C in range(2 if even else 1, CMAX + 1, 2 if even else 1):
            gv, hit = level(n, C)
            ngv += gv; nhit += hit
            if gv and not hit and least is None: least = C
        print(n, ngv, nhit, least, flush=True)
