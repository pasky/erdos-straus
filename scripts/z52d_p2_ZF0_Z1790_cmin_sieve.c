/* Z1790: sieve-accelerated C-form census (same output semantics as scripts/z52d_p2_SK2_cmin_seg.c, minus u,B for C<=3).
   For primes p = 1 (mod 4) in (LO, HI]: Cmin = least C <= CAP such that 4Cp+1 has a divisor d = -1 (mod 4C).
   Levels C = 1, 2, 3 are decided by a segmented sieve: (Z/4C)^* has exponent 2 for 4C | 24, so the residues of the divisors of
   N = 4Cp+1 form exactly the subgroup generated by the residues of its prime factors (each prime used 0 or 1 times), and
   -1 is a divisor residue iff it lies in that subgroup (PROVED, elementary).  We sieve N_C(x) = 4Cx+1 over the segment with
   all primes q <= sqrt(4*3*HI) (q odd, q != 3 for C = 3), keep the cofactor (1 or a prime) and the bitmask of residues mod 4C.
   Primes not resolved at C <= 3 fall back to trial division (identical routine to cmin_seg) for C = 4..CAP.
   Output: summary only (histogram of Cmin, max, zeros) unless argv[6] = "1" (then per-prime "p Cmin").
   Usage: LO HI CAP NPROC K [dump]   (NPROC/K: segment-interleaved parallelism) */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <math.h>
#include <stdint.h>
typedef unsigned long long u64;
static u64 *sp; static long nsp = 0;
static u64 divs_check(u64 N, u64 m) {
  u64 ps[64]; int es[64]; int k = 0; u64 M = N;
  for (long i = 0; i < nsp && (u64)sp[i] * sp[i] <= M; i++)
    if (M % sp[i] == 0) { int e = 0; while (M % sp[i] == 0) { M /= sp[i]; e++; } ps[k] = sp[i]; es[k] = e; k++; }
  if (M > 1) { ps[k] = M; es[k] = 1; k++; }
  int ex[64]; memset(ex, 0, sizeof(ex));
  while (1) {
    u64 r = 1 % m, dd = 1;
    for (int i = 0; i < k; i++) for (int e = 0; e < ex[i]; e++) { r = (r * (ps[i] % m)) % m; dd *= ps[i]; }
    if (r == m - 1) return dd;
    int i = 0; while (i < k) { ex[i]++; if (ex[i] <= es[i]) break; ex[i] = 0; i++; }
    if (i == k) break;
  }
  return 0;
}
static u64 inv(u64 a, u64 m) { long long t = 0, nt = 1; long long r = m, nr = a % m;
  while (nr) { long long q = r / nr, tmp = t - q * nt; t = nt; nt = tmp; tmp = r - q * nr; r = nr; nr = tmp; }
  return (u64)(t < 0 ? t + (long long)m : t); }
/* subgroup of (Z/4C)^* generated by mask contains -1 ? (exponent 2: closure under products of subsets) */
static int has_minus1(unsigned mask, int m) {
  unsigned S = 1u << 1; /* residue 1 */
  for (int r = 0; r < m; r++) if (mask >> r & 1) { unsigned T = S; for (int s = 0; s < m; s++) if (S >> s & 1) T |= 1u << ((r * s) % m); S = T; }
  return (S >> (m - 1)) & 1;
}
int main(int argc, char **argv) {
  u64 LO = strtoull(argv[1], 0, 10), HI = strtoull(argv[2], 0, 10);
  u64 CAP = strtoull(argv[3], 0, 10); long NP = atol(argv[4]), K = atol(argv[5]); int dump = argc > 6 && argv[6][0] == '1';
  u64 SQH = (u64)sqrt((double)HI) + 2;
  u64 SQT = (u64)sqrt(4.0 * (double)CAP * (double)HI + 1.0) + 2;
  u64 SQ3 = (u64)sqrt(12.0 * (double)HI + 1.0) + 2;
  char *isc = calloc(SQT + 1, 1); sp = malloc(sizeof(u64) * (SQT / 2 + 10));
  for (u64 i = 2; i <= SQT; i++) if (!isc[i]) { sp[nsp++] = i; for (u64 j = i * i; j <= SQT; j += i) isc[j] = 1; }
  long n3 = 0; while (n3 < nsp && sp[n3] <= SQ3) n3++;
  /* roots r[C][i] = -(4C)^{-1} mod q for odd q not dividing 4C */
  u64 *root[4]; for (int C = 1; C <= 3; C++) { root[C] = malloc(sizeof(u64) * n3);
    for (long i = 0; i < n3; i++) { u64 q = sp[i]; if (q == 2 || (4 * C) % q == 0) { root[C][i] = ~0ULL; continue; } root[C][i] = (q - inv((4 * C) % q, q)) % q; } }
  const u64 SEG = 1ULL << 24;
  char *seg = malloc(SEG); u64 *rem = malloc(sizeof(u64) * SEG); uint16_t *msk = malloc(sizeof(uint16_t) * SEG);
  int32_t *pidx = malloc(sizeof(int32_t) * SEG); u64 *plist = malloc(sizeof(u64) * SEG); unsigned char *cm = malloc(SEG);
  u64 hist[25] = {0}, nprim = 0, mx = 0, mxp = 0, nfall = 0; char zeros[100000]; zeros[0] = 0;
  long segno = 0;
  for (u64 lo = LO + 1; lo <= HI; lo += SEG, segno++) {
    if (segno % NP != K) continue;
    u64 hi = lo + SEG - 1; if (hi > HI) hi = HI; u64 len = hi - lo + 1;
    memset(seg, 1, len);
    for (long i = 0; i < nsp && sp[i] <= SQH; i++) { u64 q = sp[i];
      u64 start = ((lo + q - 1) / q) * q; if (start < q * q) start = q * q;
      for (u64 j = start; j <= hi; j += q) seg[j - lo] = 0; }
    long np = 0;
    for (u64 x = lo; x <= hi; x++) { pidx[x - lo] = -1; if (seg[x - lo] && x >= 5 && x % 4 == 1) { pidx[x - lo] = np; plist[np] = x; cm[np] = 0; np++; } }
    for (int C = 1; C <= 3; C++) {
      u64 m = 4 * C;
      for (long t = 0; t < np; t++) { rem[t] = m * plist[t] + 1; msk[t] = 0; }
      for (long i = 0; i < n3; i++) { u64 r = root[C][i]; if (r == ~0ULL) continue; u64 q = sp[i];
        u64 off = (r + q - lo % q) % q; unsigned qb = 1u << (q % m);
        for (u64 j = off; j < len; j += q) { long t = pidx[j]; if (t < 0 || cm[t]) continue;
          msk[t] |= qb; while (rem[t] % q == 0) rem[t] /= q; } }
      for (long t = 0; t < np; t++) { if (cm[t]) continue; unsigned mk = msk[t]; if (rem[t] > 1) mk |= 1u << (rem[t] % m);
        if (has_minus1(mk, (int)m)) cm[t] = C; }
    }
    for (long t = 0; t < np; t++) { u64 x = plist[t]; u64 found = cm[t];
      if (!found) { nfall++; for (u64 C = 4; C <= CAP && !found; C++) { u64 N = 4 * C * x + 1; if (divs_check(N, 4 * C)) found = C; } }
      nprim++; hist[found <= 20 ? found : (found ? 21 : 0)]++;
      if (found > mx) { mx = found; mxp = x; }
      if (!found && strlen(zeros) < 99000) { char b[32]; sprintf(b, " %llu", x); strcat(zeros, b); }
      if (dump) printf("%llu %llu\n", x, found); }
  }
  printf("# (%llu,%llu] K=%ld/%ld primes=%llu fallback=%llu maxCmin=%llu at %llu zeros(<=CAP):%s hist:", LO, HI, K, NP, nprim, nfall, mx, mxp, zeros);
  for (int i = 0; i < 22; i++) if (hist[i]) printf(" %d:%llu", i, hist[i]); printf("\n");
  return 0;
}
