"""review_fms_box.py R — R191 check of FIXED_MODULUS_SHOTS Thm 3.1 statistics and Cor 3.2.

For primes r ≡ 3 (mod 4), r < R: Box(k) = {c j^{-1} mod r : cj | k}, k = (r+1)/4; A_r = -Box(k).
  * statistics: mean / max |A_r|, max |A_r|/r for r > 1e3, r > 1e5;
  * every box element is a quadratic residue mod r (Remark 2.5 consequence);
  * Cor 3.2 comparison: for S = set of primes of k (so k is an S-unit), is Box(k) ⊆ 4·<S>^2 (the ES^(S) residue
    set of O186 Prop 2.1, Q ranging over the monoid <S>; mod r its image is the group generated by S)?
  * the document's example r = 11, S = {3}, p = 43.
"""
import sys

R = int(sys.argv[1]) if len(sys.argv) > 1 else 10 ** 6
L = R + 2
spf = list(range(L + 1))
i = 2
while i * i <= L:
    if spf[i] == i:
        for k in range(i * i, L + 1, i):
            if spf[k] == k:
                spf[k] = i
    i += 1


def fac(n):
    f = {}
    while n > 1:
        q = spf[n]
        f[q] = f.get(q, 0) + 1
        n //= q
    return f


def divs(n):
    ds = [1]
    for q, a in fac(n).items():
        ds = [d * q ** e for d in ds for e in range(a + 1)]
    return ds


def box(r):
    k = (r + 1) // 4
    D = divs(k)
    return {c * pow(j, -1, r) % r for c in D for j in D if (k // c) % j == 0}


def subgroup(gens, r):
    G = {1}
    frontier = [1]
    while frontier:
        nxt = []
        for a in frontier:
            for g in gens:
                b = a * g % r
                if b not in G:
                    G.add(b)
                    nxt.append(b)
        frontier = nxt
    return G


n = tot = mx = 0
mxr = None
dens3 = dens5 = 0.0
nonqr = 0
notcontained = 0
ncheck = 0
for r in range(7, R, 4):
    if spf[r] != r:
        continue
    B = box(r)
    n += 1
    tot += len(B)
    if len(B) > mx:
        mx, mxr = len(B), r
    if r > 1000:
        dens3 = max(dens3, len(B) / r)
    if r > 100000:
        dens5 = max(dens5, len(B) / r)
    if any(pow(b, (r - 1) // 2, r) != 1 for b in B):
        nonqr += 1
    if r < 20000:  # containment Box(k) ⊆ 4<S>^2 with S = primes of k (subgroup enumeration is O(r))
        S = list(fac((r + 1) // 4)) or [1]
        G = subgroup(S, r)
        coset = {4 * g * g % r for g in G}
        ncheck += 1
        if not B <= coset:
            notcontained += 1
print(f"primes r ≡ 3 mod 4, 7 <= r < {R}: {n}; mean |A_r| {tot / n:.1f}; max {mx} at r = {mxr}; "
      f"max density r>1e3 {dens3:.4f}, r>1e5 {dens5:.4f}")
print(f"boxes containing a non-residue: {nonqr}")
print(f"Cor 3.2: r < 20000 checked {ncheck}; Box(k) NOT inside ES^(S) coset 4<S>^2 (S = primes of k): {notcontained}")
r, B = 11, box(11)
print("r = 11: Box(3) =", sorted(B), "; ES^(S) S={3} residues 4<3>^2 =", sorted({4 * g * g % 11 for g in subgroup([3], 11)}))
p, Q = 43, 27
print(f"p = 43: -p mod 11 = {-p % 11}; 43 + 4*27^2 = {p + 4 * Q * Q} = 11 * {(p + 4 * Q * Q) // 11}, "
      f"divisible: {(p + 4 * Q * Q) % 11 == 0}")
