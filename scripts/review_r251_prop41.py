"""R251: sanity checks for MENU_STERILITY Prop 4.1 / Prop 4.3 at mu = 0 of c*2^s + 1, c + 1 = 4^i.
Prop 4.1 reduces to: for a window m = 3 (4), d(rho) is a positive element of Z[1/2] whose odd primes divide
N0 = 4^i + m, and d = -K = -4^(i-1) (mod m) is needed. Check: the subgroup of (Z/m)^x generated by 2 and the odd
primes of N0 contains -4^(i-1) only if m = 3 (mod 8)  (and then only with odd 2-exponent).
Also: with NEGATIVE d(rho) allowed (sign not controlled) m = 7 (8) would be possible -- shows the positivity step matters."""
from sympy import primefactors
from math import gcd

def reach(m, gens):
    seen = {1}; fr = [1]
    while fr:
        nf = []
        for x in fr:
            for g in gens:
                y = x*g % m
                if y not in seen:
                    seen.add(y); nf.append(y)
        fr = nf
    return seen

for i in (1, 2, 3):
    viol, neg_ok = [], []
    for m in range(3, 3000, 4):
        N0 = 4**i + m
        gens = [2] + [q for q in primefactors(N0) if q != 2]
        gens = [g % m for g in gens if gcd(g, m) == 1]
        target = (-pow(4, i-1, m)) % m
        R = reach(m, gens)
        if target in R and m % 8 == 7:
            viol.append(m)
        if (m - target) % m in R and m % 8 == 7:   # d(rho) negative: need -d = K
            neg_ok.append(m)
    print('i =', i, ' m=7(8) reaching -K with d(rho)>0:', viol[:10], ' with d(rho)<0 allowed:', len(neg_ok), neg_ok[:5])
