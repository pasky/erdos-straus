import sys, signal
from math import gcd, prod
from cypari2 import Pari
pari = Pari(); pari.allocatemem(512 << 20, 1 << 30, silent=True)
HMAX = int(sys.argv[1]) if len(sys.argv) > 1 else 81
HT6 = 151
class TO(Exception): pass
def _al(*a): raise TO
signal.signal(signal.SIGALRM, _al)

def factor(n):
    F = pari.factor(n)
    out = [(int(q), int(e)) for q, e in zip(F[0], F[1])]
    assert prod(q ** e for q, e in out) == n and all(pari.isprime(q) for q, e in out)
    return out

class Grp:
    def __init__(self, n, fac=None):
        self.n = n; self.fac = fac or factor(n)
        self.blocks = []
        for q, e in self.fac:
            m = q ** e; o = (q - 1) * q ** (e - 1)
            self.blocks.append((m, o, pari.znprimroot(m)))
        self.orders = [o for _, o, _ in self.blocks]
    def log(self, x):
        return [int(pari.znlog(pari.Mod(x, m), g, o)) for m, o, g in self.blocks]
    def order(self):
        return prod(self.orders)
    def index(self, vecs, coords=None):
        """index of <vecs> in the product of the selected cyclic blocks"""
        cs = list(range(len(self.orders))) if coords is None else coords
        r = len(cs)
        if r == 0: return 1
        cols = [[v[c] for c in cs] for v in vecs] + [[self.orders[cs[i]] if i == k else 0 for k in range(r)] for i in range(r)]
        Mt = pari.matrix(r, len(cols), [cols[c][k] for k in range(r) for c in range(len(cols))])
        return abs(int(pari.matdet(pari.mathnf(Mt))))
    def size(self, vecs, coords=None):
        cs = list(range(len(self.orders))) if coords is None else coords
        return prod(self.orders[c] for c in cs) // self.index(vecs, cs)

def ordmod(x, n):
    return int(pari.znorder(pari.Mod(x, n)))

def t6_formal(h):
    S = [a for a in range(1, h) if gcd(a, h) == 1]; ix = {a: i for i, a in enumerate(S)}; n = len(S)
    I = [[1 if i == 0 else 0 for i in range(n)]]  # placeholder
    basis = []
    for a in S[1:]:
        v = [0] * n; v[ix[a]] += 1; v[ix[S[0]]] -= 1; basis.append(v)   # Z-basis of I
    sig = lambda v: [v[ix[(a * pow(2, -1, h)) % h]] for a in S]       # (sigma v)_a = v_{a/2}
    img = [[x - y for x, y in zip(sig(v), v)] for v in basis]        # (sigma-1)I, in I
    # coordinates in the basis e_a - e_{S0}: drop the S0 coordinate
    Mt = pari.matrix(n - 1, len(img), [img[c][r + 1] for r in range(n - 1) for c in range(len(img))])
    snf = [int(x) for x in pari.matsnf(Mt)]
    tors = sorted(x for x in snf if x > 1); free = sum(1 for x in snf if x == 0)
    o = ordmod(2, h); t = n // o
    exp_t = [o] if o > 1 else []
    return (free, tors) == (t - 1, exp_t), (free, tors, t - 1, o)

def run(h):
    H = 2 ** h - 1; G = Grp(H)
    S = [a for a in range(1, h) if gcd(a, h) == 1]
    B = lambda a: (1 + pow(2, a % h, H)) % H
    D = lambda a: (pow(2, a % h, H) - 1) % H
    lg = {}
    def L(x):
        x %= H
        if x not in lg: lg[x] = G.log(x)
        return lg[x]
    inv = lambda x: pow(x, -1, H)
    R1 = [L(B(a) * inv(B(1))) for a in S]
    Rh = [L(B(a) * inv(B(gcd(a, h)))) for a in range(1, h)]
    C = [L(D(a)) for a in S]
    o = ordmod(2, h); t = len(S) // o
    allc = list(range(len(G.orders)))
    assert G.index(C + R1) == G.index(C)
    CR1 = G.size(C) // G.size(R1)
    msgs = []
    # (T6s) predictions
    if h % 3:
        if t == 1: assert CR1 == 1, ('C!=R1 transitive', h)
        if t == 2 and (h - 1) % h not in {pow(2, i, h) for i in range(o)}: assert CR1 <= 2, ('S=+-<2>', h, CR1)
        # R1 contains every unit-index B_a and 2:
        assert G.index(R1 + [L(B(1))]) == G.index(R1) and G.index(R1 + [L(2)]) == G.index(R1)
    msgs.append(f'h={h} t={t} o={o} [C:R1]={CR1} [U:R_h]={G.index(Rh)}')
    # (PL) primitive prime-power layer
    F = factor(h)
    if len(F) == 1 and F[0][0] >= 5:
        p, j = F[0]; N = H // (2 ** (h // p) - 1)
        cs = [i for i, (q, e) in enumerate(G.fac) if N % q == 0]
        assert prod(G.fac[i][0] ** G.fac[i][1] for i in cs) == N
        sR1 = G.size(R1, cs); sRh = G.size(Rh, cs); sC = G.size(C, cs)
        assert sRh == sR1, ('proj R_h != proj R1', h)
        neg = L(H - 1); pv = L(p)
        m1 = G.index(R1 + [neg], cs) == G.index(R1, cs); mp = G.index(R1 + [pv], cs) == G.index(R1, cs)
        Q = {pow(2, i, h) for i in range(o)}
        if o % 2 and t == 2 and h - 1 not in Q: assert m1 == mp, ('p in R1 iff -1 in R1 fails', h)
        msgs.append(f'  layer N=Phi_{h}(2): [C_N:projR1]={sC // sR1}  [U(N):projR_h]={G.index(Rh, cs)}  -1 in projR1: {m1}  p in projR1: {mp}')
    # (T7) old support
    for d in range(3, h, 2):
        if h % d: continue
        M = 2 ** d - 1; Gd = Grp(M)
        Rd = []
        for a in range(1, d):
            Rd.append(Gd.log((1 + 2 ** a) * pow(1 + 2 ** gcd(a, d), -1, M) % M))
        cs = [i for i, (q, e) in enumerate(G.fac) if M % q == 0]
        A = prod(G.fac[i][0] ** G.fac[i][1] for i in cs)
        assert A % M == 0
        assert ordmod(2 ** d, A) == A // M
        iA = G.index(Rh, cs); iM = Gd.index(Rd)
        assert iA == iM, ('T7 index', h, d, iA, iM)
        # full global index = old index * [U(J): {y:(1,y) in R}]
        csJ = [i for i in allc if i not in cs]
        kernel_part = G.index(Rh) // iA
        msgs.append(f'  T7 d={d}: [U(A):im R_h]={iA}=[U(M):R_d]; global/old={kernel_part}')
    # (T8) squarefree prime insertion
    for p, e in F:
        d = h // p
        if p == 2 or d == 1 or e > 1 or gcd(p, d) > 1 or (2 ** d - 1) % p == 0: continue
        M = 2 ** d - 1; f = ordmod(p, d)
        csM = [i for i, (q, ee) in enumerate(G.fac) if M % q == 0]
        csN = [i for i in allc if i not in csM]
        split_defect = G.size(Rh, csM) * G.size(Rh, csN) // G.size(Rh)
        bad = [int(q) for q in (pari.factor(split_defect)[0] if split_defect > 1 else [])]
        assert all((p ** f - 1) % q == 0 for q in bad), ('T8', h, p, split_defect)
        msgs.append(f'  T8 p={p} d={d} f={f}: split defect {split_defect} primes {bad} | p^f-1={p ** f - 1}')
    return msgs

def main():
    bad6 = []
    for h in range(3, HT6 + 1, 2):
        ok, info = t6_formal(h)
        if not ok: bad6.append((h, info))
    print(f'(T6) Smith form I/(sigma-1)I = Z^(t-1)+Z/o for all odd 3<=h<={HT6}: {not bad6}', bad6[:5])
    done = []; skipped = []
    for h in range(3, HMAX + 1, 2):
        signal.alarm(120)
        try:
            for line in run(h): print(line, flush=True)
            done.append(h)
        except TO:
            skipped.append(h)
        finally:
            signal.alarm(0)
    print('group checks done for', len(done), 'odd h; timeouts:', skipped)

if __name__ == '__main__':
    main()
